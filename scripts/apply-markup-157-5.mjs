function patch(path, listKey, idKey, map) {
  const cfg = JSON.parse(readFileSync(path, "utf8"));
  let touched = 0;
  const missed = [];
  for (const rec of cfg[listKey] ?? []) {
    const m = map[rec[idKey]];
    if (!m) {
      missed.push(rec[idKey]);
      continue;
    }
    rec.tags = m.tags;
    rec.triggers = m.triggers;
    rec.answers = m.answers;
    touched += 1;
  }
  writeFileSync(path, `${JSON.stringify(cfg, null, 2)}\n`);
  console.log(`${path}: размечено ${touched}, без разметки ${missed.length}${missed.length ? " — " + missed.join(", ") : ""}`);
  return missed.length;
}

