// ПРИБОР ПОДШАГА 164-9 — СПЛОШНАЯ РЕВИЗИЯ: ЧТО ПОСТРОЕНО И НЕ ОПИСАНО.
//
// 🎯 СЛОВО ВЛАДЕЛЬЦА 2026-09-09: «в документации, как я понимаю, вы забыли
// добавить одно требование, которое мы реализовали… Что ещё не добавил в
// описании — повтори исследование документации и наполни наше описание памяти».
//
// 🔒 ПОЧЕМУ ЭТО ПРИБОР, А НЕ ПЕРЕЧИТЫВАНИЕ. Ровно этим способом и была потеряна
// разметка «утверждение / предположение»: документ читали целиком, он выглядел
// связным, и отсутствие раздела никому не бросилось в глаза. Отсутствие вообще
// не бросается в глаза — его находят списком, а не чтением.
//
// 🔒 У ПРОВЕРКИ ОТСУТСТВИЯ ЕСТЬ СВОЙ ПОЛОЖИТЕЛЬНЫЙ ОБРАЗЕЦ (закон, оплаченный
// в 164-7): выдуманный механизм обязан дать «НЕ ОПИСАН». Без него список зелен
// по причине собственной слепоты.
//
// Ничего не пишет и никуда не ходит: читает три файла на диске.
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const MARK = "===PROBE_164_9==="
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "../..")
// Путь можно подменить — этим снимается «до»: та же ревизия против ПРЕЖНЕЙ
// редакции документа обязана дать красное. Проверка, которая зелена на обеих
// редакциях, не проверяет ничего.
const docPath = process.env.MEMORY_DOC || join(root, "development-docs/MEMORY.md")
const doc = readFileSync(docPath, "utf8")
const decl = readFileSync(join(root, "lib/memory/decl.mjs"), "utf8")

let bad = 0
const say = (ok, what) => { if (!ok) bad += 1; console.log(`${ok ? "✓" : "✗"} ${what}`) }
// 🛑 ПЕРЕНОС СТРОКИ ЛОМАЛ ПРОВЕРКУ. Фраза «только с разрешения архитектора»
// живёт в документе на двух строках, и образец не совпадал при полностью
// описанном механизме. Ложное «НЕ ОПИСАН» так же вредно, как ложное «описан»:
// по нему чинят то, что не сломано. Отсюда сплющивание пробелов у обеих сторон.
const flat = doc.replace(/\s+/g, " ").toLowerCase()
const inDoc = s => flat.includes(s.replace(/\s+/g, " ").toLowerCase())

// Механизм → слова, по которым видно, что он в документе ОПИСАН, а не упомянут.
// Адрес в коде стоит рядом: строка без адреса — обещание, а не механизм.
const MECHANISMS = [
  ["четыре действия одной дверью", "lib/memory/decl.mjs", ["запомнить, ответить, поправить, забыть"]],
  ["каскад из трёх слоёв", "lib/memory/box.ts", ["каскад", "первый слой", "второй"]],
  ["правило: куда попадёт сведение", "lib/memory/box.ts", ["решает расстояние от архитектора"]],
  ["якорь: без привязки не найдётся", "lib/memory/box.ts", ["не находится ни одним вопросом"]],
  ["охват: где сведение верно", "lib/facts/*", ["область, в которой оно истинно"]],
  ["утверждение и предположение", "lib/facts/write.ts:146", ["утверждение и предположение — два рода значения"]],
  ["основание обязательно у предположения", "lib/facts/write.ts:146", ["у него **обязательно есть\nоснование**"]],
  ["субъект: чей это факт", "lib/memory/decl.mjs", ["субъект"]],
  ["три рода записей об окружении", "lib/memory/box.ts", ["трёх родов"]],
  ["пустой род значит «не назван»", "lib/facts/write.ts", ["не назван"]],
  ["журнал промахов формулировки", "lib/registry/*", ["журнал промахов"]],
  ["справочник с диска действует немедленно", "REGISTRY-CONFIG/", ["без пересборки и перезапуска"]],
  ["кандидатов предлагает система, заводит человек", "lib/automations/fact-proposal.ts", ["сама её не заводит"]],
  ["глубина, цена и разрешение", "lib/memory/box.ts", ["разрешения архитектора"]],
  ["передача находок следующему слою", "lib/memory/box.ts", ["становится запросом к графу"]],
  ["предфильтр по меткам графа", "lib/memory/box.ts", ["знает ли граф такое имя"]],
  ["знакомство по ходу дела", "lib/memory/box.ts (acquaint)", ["анкету человек не проходит"]],
  ["положительное дообучение только после «да»", "lib/memory/box.ts", ["после согласия архитектора"]],
  ["отрицательное дообучение без спроса", "lib/memory/box.ts", ["без вопросов"]],
  ["удаление оставляет определение", "lib/memory/decl.mjs", ["удаляется значение, а не умение"]],
  ["связь сведения с номером работы", "automation_facts", ["по номеру автоматизации"]],
  ["хранится то, что не меняется само", "REGISTRY-CONFIG/", ["не меняется само"]],
  ["три несмешиваемые глубины", "MEMORY-STANDARD §2.2", ["три несмешиваемые вещи"]],
  ["язык описаний в связях", "SUMMARY_LANGUAGE", ["английские описания"]],
  ["чего пока нет — названо честно", "—", ["чего пока нет"]],
]

console.log(MARK)
console.log(`ревизия: ${MECHANISMS.length} механизмов против ${docPath} (${doc.split("\n").length} строк)`)

for (const [name, where, markers] of MECHANISMS) {
  const hit = markers.some(m => inDoc(m))
  say(hit, `${hit ? "описан" : "НЕ ОПИСАН"}: ${name}  ·  живёт в ${where}`)
}

// Каждый метод ящика обязан быть узнаваем в документе для человека.
const methods = [...decl.matchAll(/name: "memory_(\w+)"/g)].map(m => m[1])
const RU = { forget: "удаление", mutate: "изменени", read: "чтение", write: "запись" }
for (const m of methods) {
  say(inDoc(RU[m] ?? m), `метод memory_${m} узнаваем в документе как «${RU[m] ?? m}»`)
}

// 🔒 ПОЛОЖИТЕЛЬНЫЙ ОБРАЗЕЦ ДЛЯ САМОЙ ПРОВЕРКИ ОТСУТСТВИЯ.
const ghost = "механизм, которого в этом продукте не существует"
say(!inDoc(ghost), `контроль слепоты: выдуманный механизм даёт «НЕ ОПИСАН», как и должен`)

console.log(`${MARK}DONE`)
console.log(`PROBE_RC=${bad === 0 ? 0 : 1}`)
process.exit(bad === 0 ? 0 : 1)
