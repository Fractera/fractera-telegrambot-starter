import { type NextRequest, NextResponse } from "next/server";

// ЕДИНАЯ ТОЧКА ВХОДА (наша правка поверх шаблона, шаг 96).
//
// 🔒 ТРЕБОВАНИЕ ВЛАДЕЛЬЦА ДОСЛОВНО: «где бы ни вошли — хоть админпанель, хоть
// сайт, хоть чат — всё делает переадресацию к единственной точке входа».
// Поэтому гостевой вход шаблона (`/api/auth/guest`) здесь больше не зовётся: он
// заводил бы вторую правду о человеке — чат знал бы своих, проект своих.
//
// 🔒 ПРОКСИ ЗНАЕТ ТОЛЬКО «ВОШЁЛ ИЛИ НЕТ». Личность и роли читает `auth()` на
// странице; прокси не должен знать о человеке больше, чем нужно для
// переадресации, — тот же порядок, что в гостевом приложении.
//
// 🔒 КУКА ВИДНА ЧАТУ, И ЭТО ИЗМЕРЕНО: служба входа ставит её на
// `COOKIE_DOMAIN=.aifa.dev`, то есть на весь домен второго уровня.
//
// 🛑 АДРЕСА СОБИРАЮТСЯ ИЗ ЗАГОЛОВКОВ NGINX, А НЕ ИЗ `request.url`. ✗ оплачено
// трижды за день: за прокси внутренний адрес выглядит как `localhost:3600`, и
// любая построенная из него ссылка ведёт в никуда с чужой машины.

function publicOrigin(request: NextRequest): string {
  const host =
    request.headers.get("x-forwarded-host") ?? request.headers.get("host") ?? "";
  const proto = request.headers.get("x-forwarded-proto") ?? "https";
  return host ? `${proto}://${host}` : new URL(request.url).origin;
}

// 🔒 ЯЗЫКИ СЛУЖБЫ — ДВА, И СПИСОК ЗДЕСЬ ЕДИНСТВЕННЫЙ. Второй перечень рядом с
// настоящим разошёлся бы молча: страница на языке, которого нет в списке,
// оказалась бы за замком без причины.
const SUPPORTED = ["ru", "en"];

// 🔒 АДРЕС СЛУЖБЫ ВХОДА ВЫВОДИТСЯ ИЗ ХОСТА, А НЕ ХРАНИТСЯ КОНСТАНТОЙ — зеркало
// приёма с порта 3000. На домене это `auth.<апекс>`, на голом IP — соседний
// порт. Ссылка в разметке про это не знает и знать не должна.
function publicAuthOrigin(request: NextRequest): string {
  const host =
    request.headers.get("x-forwarded-host") ?? request.headers.get("host") ?? "";
  const proto = request.headers.get("x-forwarded-proto") ?? "https";
  if (!host) {
    return process.env.NEXT_PUBLIC_AUTH_URL ?? "http://localhost:3001";
  }
  // Голый IP с портом: служба входа живёт соседним портом на той же машине.
  // ✗ ЗДЕСЬ СТОЯЛО `(d+)` ВМЕСТО `(\d+)` — ПОТЕРЯННЫЙ СЛЭШ, И ОН ПРОЖИЛ ТРИ ДНЯ.
  // 🔒 ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО: старый образец совпадал НЕ НИКОГДА, а ХУЖЕ —
  // только с бессмыслицей вроде `213.199.61.7:d`, и ни разу с настоящим
  // `213.199.61.7:3600`. То есть он и пропускал верное, и принимал неверное.
  // На голом IP человек уходил в ветку домена и получал адрес вида
  // `https://auth.213.199.61.7:3000` — службы по нему нет.
  // 🛑 НА ДОМЕНЕ ЭТО МОЛЧИТ ЦЕЛИКОМ: ветка IP там не исполняется, и дефект
  // виден только на свежем сервере в режиме без домена — то есть у КЛИЕНТА,
  // в его первый день, а не у нас.
  // 🔒 ПРИЧИНА ОПЕЧАТКИ НАЗВАНА, ЧТОБЫ НЕ ПОВТОРИТЬ: строка писалась через
  // `node -e` в оболочке, и обратный слэш съела она же — тот самый класс, что
  // за эту сессию сработал четырежды.
  const m = host.match(/^([^:]+):(\d+)$/);
  if (m) {
    return `${proto}://${m[1]}:3001`;
  }
  // Домен: `chat.aifa.dev` → `auth.aifa.dev`. Первый ярлык заменяется, апекс цел.
  const parts = host.split(".");
  const apex = parts.length > 2 ? parts.slice(1).join(".") : host;
  return `${proto}://auth.${apex}`;
}

export async function proxy(request: NextRequest) {
  const { pathname } = request.nextUrl;

  if (pathname.startsWith("/ping")) {
    return new Response("pong", { status: 200 });
  }

  // 🔒 ССЫЛКИ ВХОДА И ВЫХОДА УВОДЯТСЯ В СЛУЖБУ — ЗЕРКАЛО ПОРТА 3000 (156-1).
  // Островок главной страницы шлёт ОТНОСИТЕЛЬНЫЕ `/login` и `/logout`, как на
  // 3000: адрес службы входа выводится из хоста здесь, а не в разметке. Иначе
  // ссылка знала бы про домен, и на голом IP она вела бы в никуда.
  // 🔒 ВЫХОДУ ПРИКЛАДЫВАЕТСЯ АДРЕС ВОЗВРАТА: служба чистит куку и обязана
  // вернуть человека СЮДА, а вывести наш адрес сама она не может — порт и
  // поддомен у каждой службы свои.
  if (pathname === "/login" || pathname === "/register" || pathname === "/logout") {
    const search = new URLSearchParams(request.nextUrl.search);
    if (pathname === "/logout" && !search.has("redirectUrl")) {
      // 🔒 ЯЗЫК БЕРЁТСЯ ИЗ ТОГО, ЧТО ПРИСЛАЛ ОСТРОВОК, А НЕ ИЗ АДРЕСА ВЫХОДА.
      // У `/logout` языкового сегмента нет по устройству, и `langOf()` там
      // падает на заголовок браузера — русского человека выход возвращал бы на
      // английскую главную. ✗ измерено: `redirectUrl` указывал на `/en` при
      // `?lang=ru` в самой ссылке. Зеркало 3000: там читают ровно этот параметр.
      const asked = search.get("lang") ?? "";
      const back = SUPPORTED.includes(asked) ? asked : langOf(request);
      // 🔒 ПОСЛЕ ВЫХОДА — СТРАНИЦА ПРИВЕТСТВИЯ, А НЕ ГЛАВНАЯ (179-2, слово
      // владельца 2026-09-10: «after success logout to do welcome page… в обоих
      // проектах»). Там две дороги — войти снова или вернуться на главную;
      // главная сама по себе не говорит человеку, что он только что вышел.
      search.set("redirectUrl", `${publicOrigin(request)}/${back}/welcome`);
    }
    const qs = search.toString();
    const away = NextResponse.redirect(
      `${publicAuthOrigin(request)}${pathname}${qs ? `?${qs}` : ""}`
    );

    // 🛑 ВЫХОД ЧИСТИТ КУКУ И НА НАШЕМ ХОСТЕ — БЕЗ ЭТОГО ОН НЕ РАБОТАЕТ ВОВСЕ.
    // ✗ ОПЛАЧЕНО 2026-09-07 ТРЕМЯ КРУГАМИ ОТЛАДКИ, И НАШЁЛ ЭТО ВЛАДЕЛЕЦ, А НЕ Я:
    // «на 3000 сессию потерял, а в чате всё ещё горит авторизация». Измерено:
    // `auth.aifa.dev/api/session` отвечает `Unauthorized`, а `chat.aifa.dev/api/me`
    // в тот же момент — `200` с почтой. Куки ДВЕ: одна общая, с `Domain=.aifa.dev`,
    // вторая — HOST-ONLY на нашем хосте, оставшаяся от прежнего шаблона.
    //
    // 🔒 СЛУЖБА ВХОДА ВЫЧИСТИТЬ ЕЁ НЕ МОЖЕТ ФИЗИЧЕСКИ: браузер не даёт одному
    // хосту стирать куки другого. Значит это НАША обязанность, и ничья больше.
    //
    // 🔒 ЧИСТИМ ВСЕ ИМЕНА, А НЕ ОДНО. Защищённый режим и режим без домена дают
    // разные префиксы, а старые версии библиотеки — другое имя целиком. Кука,
    // не попавшая в список, оставит человека внутри — и выглядеть это будет
    // ровно так, как выглядело: выход «не работает» без единой ошибки.
    if (pathname === "/logout") {
      for (const name of [
        "__Secure-authjs.session-token",
        "authjs.session-token",
        "__Secure-next-auth.session-token",
        "next-auth.session-token",
      ]) {
        // 🛑 ПРЕФИКС `__Secure-` ТРЕБУЕТ ФЛАГА `Secure`, ИНАЧЕ БРАУЗЕР
        // ОТКЛОНЯЕТ УСТАНОВКУ МОЛЧА — И ОЧИСТКА НЕ ПРОИСХОДИТ. ✗ оплачено в тот
        // же час: первая версия этой правки ставила пустое значение без `secure`,
        // ответ уходил с заголовком, браузер его игнорировал, и человек
        // оставался внутри — ровно как до правки. Заголовок в ответе и
        // применённая кука — разные утверждения.
        away.cookies.set(name, "", {
          httpOnly: true,
          maxAge: 0,
          path: "/",
          sameSite: "lax",
          secure: name.startsWith("__Secure-"),
        });
      }
    }
    return away;
  }

  // Родные маршруты NextAuth шаблона оставлены живыми: сносить чужой механизм
  // ради своего значит ссориться с каждым обновлением сверху.
  if (pathname.startsWith("/api/auth")) {
    return NextResponse.next();
  }

  // 🔒 СТРАНИЦА-ЗАГЛУШКА ЖИВЁТ БЕЗ СЕССИИ — иначе она отправляла бы к входу
  // того, кто на неё же и вернулся после выхода, и человек ходил бы по кругу.
  // 🔒 АДРЕС ЗАГЛУШКИ СТАЛ ЯЗЫКОВЫМ (2026-09-06): страница переехала в
  // `app/[lang]/welcome`, чтобы получить шапку, подвал и словарь. Проверка
  // по СУФФИКСУ, а не по точному пути: языков много, и перечислять их здесь
  // значило бы завести второй список языков рядом с настоящим.
  // 🛑 ГОЛЫЙ `/welcome` БЕЗ ЯЗЫКА ОТВЕЧАЛ 404 ПОСЛЕ ПЕРЕЕЗДА, И ЭТО НАШЛОСЬ
  // ЗАМЕРОМ, А НЕ ГЛАЗАМИ. Адрес прежний, на него ведут закладки и ссылка
  // выхода из панели; пропустить его дальше значило показать человеку без
  // сессии пустую страницу вместо приглашения войти.
  if (
    pathname === "/welcome" ||
    pathname === "/terminal" ||
    pathname === "/claude-subscription"
  ) {
    return NextResponse.redirect(
      `${publicOrigin(request)}/${langOf(request)}${pathname}`
    );
  }

  // 🔒 ЯЗЫКОВОЙ АДРЕС ЗАГЛУШКИ ПРОПУСКАЕТСЯ БЕЗ СЕССИИ — иначе она отправляла бы
  // к входу того, кто на неё же и вернулся после выхода, и человек ходил бы по
  // кругу.
  // 🔒 ГЛАВНАЯ СТРАНИЦА ПУБЛИЧНА (156-1, решение владельца 2026-09-07). Корень
  // и языковой корень пропускаются без сессии: это единственная поверхность,
  // которую служба показывает снаружи, и на ней стоит кнопка входа.
  // 🛑 ПРОВЕРКА ТОЧНАЯ, А НЕ ПО ПРЕФИКСУ. `/ru` пропускается, `/ru/settings` —
  // нет. Префикс открыл бы заодно всё, что появится под языком завтра, и открыл
  // бы молча — та же ошибка, от которой защищены двери выше.
  // 🔒 ДВЕРЬ «КТО ВОШЁЛ» ОТВЕЧАЕТ САМА, И ЭТО НЕ ДЫРА В ЗАМКЕ (156-1).
  // Её зовёт островок публичной главной. Перехваченная привратником, она отдаёт
  // `307` на заглушку, островок читает HTML вместо JSON и решает «гость» —
  // случайно верно, а значит вдвойне опасно: вошедший тоже увидел бы «Войти».
  // ✗ ИЗМЕРЕНО: `/api/me` без куки отвечал `307` вместо `401`.
  // 🛑 Дверь ничего не открывает: без сессии она сама отдаёт `401`.
  if (pathname === "/api/me") {
    return NextResponse.next();
  }

  // 🔒 ДВЕРЬ «ЧТО Я ЗНАЮ О ВАС» ОТВЕЧАЕТ САМА — ТОТ ЖЕ ДОВОД, ЧТО У `/api/me`
  // ВЫШЕ (158-5). Она проверяет и сессию, и роль `architect`; перехваченная
  // привратником, она отдаёт `307` на заглушку, и островок читает HTML вместо
  // JSON — то есть человек с истёкшей сессией видит «сохранить не удалось»
  // вместо «войдите заново».
  // 🛑 ИМЕНЕМ, А НЕ ПРЕФИКСОМ `/api/fractera/*`: префикс открыл бы заодно ключ
  // OpenAI, медиатеку и настройку бота, которые живут рядом.
  // 🔒 ТОТ ЖЕ ДОВОД У РЕДАКТОРА `SOUL.md` (158-5в): он проверяет сессию и роль
  // сам, и перехват отдал бы островку HTML вместо JSON.
  // 🔒 И ДВЕРЬ БИЛЕТА ТЕРМИНАЛА — ПО ТОМУ ЖЕ ДОВОДУ (найдено 2026-09-08).
  // Она проверяет сессию и роль `architect` сама и отвечает `401`/`403`.
  // ✗ ПЕРЕХВАЧЕННАЯ, ОНА ОТДАЁТ `307` НА ЗАГЛУШКУ, и островок терминала читает
  // HTML вместо JSON: `SyntaxError: Unexpected token '<'`. Человек с истёкшей
  // сессией видит не «войдите заново», а сломанный терминал — ровно тот симптом,
  // на который ушёл день отладки в 157-3.
  // 🛑 ТРЕТЬЯ ДВЕРЬ ЭТОГО ЖЕ КЛАССА ЗА ДВА ДНЯ. Признак, по которому их искать:
  // дверь сама зовёт `fracteraSession()` — значит привратник ей мешает, а не помогает.
  // 🔒 ЧЕТВЁРТАЯ — СТЕНД ПАМЯТИ (176-1, 2026-09-10), И ОНА НАЙДЕНА ПРИЗНАКОМ,
  // А НЕ ОТЛАДКОЙ. Правило из строки выше сработало как прибор: дверь зовёт
  // `fracteraSession()` сама — значит её имя обязано стоять здесь. ✗ без этой
  // строки островок стенда получил бы `307` и прочитал HTML вместо JSON, а
  // выглядело бы это как «память не отвечает» — то есть обвинён был бы ровно
  // тот, кого стенд заведён испытывать.
  if (
    pathname === "/api/fractera/known" ||
    pathname === "/api/fractera/soul" ||
    pathname === "/api/fractera/pty-ticket" ||
    pathname === "/api/fractera/misses" ||
    // 🔒 Дверь ключа OpenAI проверяет роль сама (181-2), как у памяти: перехваченная
    // привратником, она отдавала бы переадресацию вместо JSON.
    pathname === "/api/fractera/openai-key"
    // 🪦 ЗДЕСЬ СТОЯЛА ДВЕРЬ СТЕНДА ПАМЯТИ — УЕХАЛА НА СВОЮ СЛУЖБУ 2026-09-10
    // (178-4). Она была четвёртой дверью этого класса; правило, по которому её
    // сюда вписали, живо и работает — им же её отсюда и убрали, вместе с самой
    // дверью. Восстанавливается из git.
  ) {
    return NextResponse.next();
  }

  // 🛑 ГОЛЫЙ КОРЕНЬ ПЕРЕАДРЕСУЕТСЯ НА ЯЗЫКОВОЙ, А НЕ ПРОПУСКАЕТСЯ.
  // ✗ ОПЛАЧЕНО В ТОТ ЖЕ ДЕНЬ, 2026-09-07: я открыл `/` привратником, а страницы
  // у корня нет — все страницы живут под `[lang]`. Человек, набрав адрес сайта
  // без языка, получал `404`. Прибор этого не поймал, потому что я проверил
  // `/ru` и `/en` — то, что построил, — и не проверил то, что НАБИРАЕТ человек.
  // 🔒 ТОТ ЖЕ ПРИЁМ, ЧТО У `/welcome` И `/terminal` ВЫШЕ: адрес без языка
  // существует, ведёт куда надо и не требует от человека знать про сегмент.
  if (pathname === "/") {
    return NextResponse.redirect(`${publicOrigin(request)}/${langOf(request)}`);
  }

  // 🔒 ЯЗЫКОВОЙ КОРЕНЬ ПУБЛИЧЕН (156-1). Проверка точная, а не по префиксу:
  // `/ru` пропускается, `/ru/settings` — нет.
  if (SUPPORTED.some(l => pathname === `/${l}`)) {
    return NextResponse.next();
  }

  if (pathname.endsWith("/welcome")) {
    return NextResponse.next();
  }

  // 🔒 ДВЕРЬ КАНАЛОВ ЖИВЁТ БЕЗ СЕССИИ, ПОТОМУ ЧТО У СЛУЖБЫ ЕЁ НЕТ И БЫТЬ НЕ МОЖЕТ
  // (97-2). Сообщение из Telegram приносит машина `:3500`, а не браузер: кук у
  // неё нет, и привратник увёл бы её на заглушку — то есть входящее просто не
  // доезжало бы, и выглядело бы это как молчащий бот.
  //
  // 🛑 ЗАМОК НЕ СНЯТ, ОН ДРУГОЙ: дверь проверяет общий секрет заголовком
  // `X-Channel-Secret` и без него отвечает `401`. Не задан секрет — дверь не
  // принимает никого.
  //
  // 🛑 И ЭТО ЕДИНСТВЕННОЕ ТАКОЕ ИСКЛЮЧЕНИЕ. Названо поимённо, а не префиксом:
  // `/api/channels/*` открыл бы заодно всё, что здесь появится завтра, и открыл
  // бы молча. В режиме без домена разницы не видно вовсе — служба входа пускает
  // всех, — и ошибка всплыла бы уже на домене, у клиента.
  if (pathname === "/api/channels/inbound") {
    return NextResponse.next();
  }

  // 🔒 ВТОРОЕ ИСКЛЮЧЕНИЕ, И ОНО ТОЖЕ ПОИМЁННОЕ (155-2): дверь первичной
  // сепарации. Её зовёт инструмент MCP из живой сессии агента — процесс на этой
  // же машине, у которого кук нет и быть не может. Дверь проверяет общий секрет
  // машины сама и без него отвечает `401`.
  // 🛑 ПРЕФИКСОМ ЭТО НЕ ПИШЕТСЯ. `/api/agent/*` открыл бы заодно всё, что
  // появится здесь завтра, и открыл бы молча — ровно та ошибка, от которой
  // защищает соседнее исключение выше.
  // 🔒 ЧЕТВЁРТОЕ ИСКЛЮЧЕНИЕ (143-6): дверь отзыва. Её зовёт тот же инструмент
  // MCP из живой сессии — процесс на этой машине без кук. Секрет проверяет сама.
  // 🛑 И ОПЯТЬ ПОИМЁННО. Четыре имени подряд выглядят как повод завести префикс —
  // это и есть та минута, в которую его заводят, а завтра под него молча
  // попадает пятая дверь, которую никто не собирался открывать.
  // 🔒 ТРЕТЬЕ ИСКЛЮЧЕНИЕ (157-5): единый вход в реестры. Его зовёт тот же
  // инструмент MCP из живой сессии агента — процесс на этой машине, у которого
  // кук нет и быть не может. Дверь проверяет общий секрет машины сама.
  // 🛑 ИМЯ ДОБАВЛЕНО ПОИМЁННО, А НЕ ПРЕФИКСОМ `/api/agent/*` — по той же причине,
  // что у двух соседей выше: префикс открыл бы заодно всё, что появится здесь
  // завтра, и открыл бы молча.
  if (
    pathname === "/api/agent/separate" ||
    pathname === "/api/agent/close" ||
    pathname === "/api/agent/registry" ||
    pathname === "/api/agent/feedback" ||
    pathname === "/api/agent/knowledge" ||
    // 🔒 ШЕСТОЕ ИСКЛЮЧЕНИЕ (161-1): ящик памяти. Тот же инструмент MCP из живой
    // сессии агента, тот же общий секрет машины, проверяемый самой дверью.
    // 🛑 И СНОВА ПОИМЁННО — ШЕСТОЕ ИМЯ ПОДРЯД. Соблазн завести префикс здесь
    // сильнее, чем на четвёртом, и именно поэтому запрет повторяется: префикс
    // откроет седьмую дверь ЗАРАНЕЕ и молча, а узнаем мы об этом от того, кто
    // ею воспользуется.
    // ✗ ОПЛАЧЕНО ИЗМЕРЕНИЕМ В ТОТ ЖЕ ЧАС: дверь была построена, собрана и
    // отвечала `200` со страницей входа — прибор видел «непостроенный метод
    // вернул 200» и не мог назвать причину. Форма отказа привратника —
    // перенаправление, а не ошибка, и потому она неотличима от ответа двери.
    pathname === "/api/agent/memory"
  ) {
    return NextResponse.next();
  }

  // 🛑 СПРАШИВАЕМ СЛУЖБУ ДАЖЕ БЕЗ ЕДИНОЙ КУКИ — ЭТО ПРО РЕЖИМ БЕЗ ДОМЕНА.
  // Здесь стояло `if (cookie)`: без кук привратник никого не спрашивал и сразу уводил на
  // заглушку. В защищённом режиме разницы нет — служба и так ответила бы `401`. Но свежий
  // сервер живёт на голом IP, и там служба входа отдаёт `demo@local` с ролью архитектора
  // ВСЕМ: панель и сайт в онбординге работают, а чат единственный отвечал бы «войдите»,
  // при том что входить ещё некуда. Цена — один запрос по петле.
  const cookie = request.headers.get("cookie") ?? "";
  let signedIn = false;
  {
    try {
      const authService =
        process.env.AUTH_SERVICE_URL ||
        process.env.NEXT_PUBLIC_AUTH_URL ||
        "http://localhost:3001";
      const res = await fetch(`${authService}/api/session`, {
        cache: "no-store",
        headers: cookie ? { cookie } : undefined,
      });
      signedIn = res.ok && Boolean(((await res.json()) as { email?: string })?.email);
    } catch {
      // 🛑 СЛУЖБА ВХОДА МОЛЧИТ — ЧЕЛОВЕК НЕ УЗНАН, И ЭТО ЧЕСТНЫЙ ИСХОД. Пускать
      // «на всякий случай» нельзя: это открыло бы чат целиком в тот момент,
      // когда одна служба не отвечает.
      signedIn = false;
    }
  }

  if (!signedIn) {
    // 🔒 СНАЧАЛА ЗАГЛУШКА, ПОТОМ ВХОД (правка владельца 2026-09-02). Прямая
    // переадресация к службе выглядела как поломка: человек нажимал «выйти» и
    // немедленно оказывался на чужой форме входа, не поняв, что вышел. Заглушка
    // объясняет, где он и что делать, и уводит дальше по нажатию.
    //
    // 🔒 СТАНДАРТ ССЫЛКИ ВЫХОДА ПРИ ЭТОМ НЕ ТРОНУТ: он общий с панелью, и второй
    // стандарт ради одного случая — это ровно то, чего мы избегаем.
    return NextResponse.redirect(`${publicOrigin(request)}/${langOf(request)}/welcome`);
  }

  // Вошедшему незачем видеть формы входа шаблона и заглушку: единственная точка
  // входа — служба, и её страницы живут по другому адресу.
  if (["/login", "/register"].includes(pathname) || pathname.endsWith("/welcome")) {
    return NextResponse.redirect(`${publicOrigin(request)}/${langOf(request)}/terminal`);
  }

  // 🔒 КОРЕНЬ СЛУЖБЫ ВЕДЁТ В ТЕРМИНАЛ АГЕНТА, А НЕ В ЛЕНТУ ЧАТА (124,
  // 2026-09-05). Решение владельца: «наша задача убрать полностью ai sdk из
  // этого проекта». Путь к ИИ один — Telegram → Claude Code; лента в нём не
  // участвует, а служба `:3600` нужна ради терминала подписки, двери канала,
  // медиатеки и расшифровки голоса.
  //
  // ✗ ПОЧЕМУ ЗДЕСЬ, А НЕ В САМОЙ СТРАНИЦЕ, И ЭТО ОПЛАЧЕНО УПАВШЕЙ СБОРКОЙ.
  // `redirect()` в `page.tsx` при включённом `cacheComponents` уезжает внутрь
  // частичного предрендеривания: ответ `200`, заголовок `x-nextjs-postponed: 1`,
  // оболочка чата статикой, переадресация уже в браузере — то есть человек
  // видит ровно тот экран, от которого уходит, а без JavaScript не уходит вовсе.
  // Попытка вылечить это `export const dynamic = "force-dynamic"` УРОНИЛА
  // СБОРКУ: «Route segment config "dynamic" is not compatible with
  // nextConfig.cacheComponents». Запрет был записан в двери `agent-setup` и
  // прочитан мной за час до нарушения.
  // 🔒 ЗДЕСЬ ЖЕ ПЕРЕАДРЕСАЦИЯ СЛУЧАЕТСЯ ДО ЕДИНОГО БАЙТА РАЗМЕТКИ и работает
  // без JavaScript — тем же приёмом, что три соседние выше.
  if (pathname === "/") {
    return NextResponse.redirect(`${publicOrigin(request)}/${langOf(request)}/terminal`);
  }

  return NextResponse.next();
}

// 🔒 ЯЗЫК ДЛЯ ПЕРЕАДРЕСАЦИИ БЕРЁТСЯ ИЗ САМОГО АДРЕСА, А НЕ ЗАШИТ (2026-09-06).
// Страницы переехали под `[lang]`, и привратник обязан уводить человека на
// СВОЙ язык: увести русского на `/en/welcome` значит показать ему чужой язык
// в первый же момент, когда он ещё не вошёл и объяснить некому.
// 🛑 СПИСКА ЯЗЫКОВ ЗДЕСЬ НЕТ НАМЕРЕННО: второй список рядом с настоящим
// разошёлся бы с ним молча. Берём первый сегмент, если он похож на код языка,
// иначе смотрим заголовок браузера, иначе английский.
function langOf(request: NextRequest): string {
  const first = new URL(request.url).pathname.split("/")[1] ?? "";
  if (/^[a-z]{2}$/.test(first)) {
    return first;
  }
  const accept = request.headers.get("accept-language") ?? "";
  return accept.toLowerCase().startsWith("ru") ? "ru" : "en";
}

