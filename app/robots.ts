// 🔒 ЗАПРЕТ ЗДЕСЬ — НЕ ОСТОРОЖНОСТЬ, А ОПИСАНИЕ ФАКТА. Служба бота целиком стоит
// за замком: её страницы спрашивают роль `architect` у службы входа и отвечают
// `404` всем остальным. Индексировать тут нечего ни одной строки, а
// отсутствующий `robots.txt` читается поисковиком как разрешение обходить всё.
//
// 🛑 ЭТО НЕ ЗАМОК И НЕ ЗАЩИТА. `robots.txt` — просьба к поисковым роботам, и
// уважают её только добросовестные. Защищает роль в `fracteraRoles()` и замки
// на дверях `/api/*`; этот файл лишь убирает службу из выдачи.
//
// 🔒 ПОЧЕМУ ФАЙЛОМ, А НЕ НАСТРОЙКОЙ. У сайта на 3000 индексацией управляет
// владелец — там это поля `seo.robotsIndex` и `seo.robotsFollow` в `APP-CONFIG`,
// и так и должно быть: сайт живёт ради посетителей. Здесь настройки нет
// намеренно: включать индексацию служебной панели незачем, а выключатель, у
// которого нет осмысленного второго положения, — приглашение его щёлкнуть.

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [{ disallow: "/", userAgent: "*" }],
  };
}
