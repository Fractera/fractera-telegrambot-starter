export type Automation = {
  /** Имя файла целиком — вечный ключ и единственный источник имени и времени. */
  file: string
  /** Человеческое имя, разобранное из имени файла. */
  name: string
  /** Время из имени файла, как его писал автор: `dd-mm-yyyy hh:mm:ss`. */
  at: string
  /** Адресный ключ страницы: имя файла без расширения. */
  id: string
  /** Сколько сообщений в цепочке. */
  steps: number
  /** Выдуманная запись, а не настоящая. */
  demo: boolean
}

/**
 * Разобрать имя файла `dd-mm-yyyy_hh-mm-ss_имя-цепочки.md`.
 *
 * 🔒 НЕРАЗБОРНОЕ ИМЯ НЕ ОТБРАСЫВАЕТСЯ, А ПОКАЗЫВАЕТСЯ КАК ЕСТЬ. Файл, чьё имя
 * не по формату, — это всё равно автоматизация; спрятав её, мы получили бы
 * список, который молча короче правды.
 */
export function parseAutomationFile(file: string): { name: string; at: string; id: string } {
  const id = file.replace(/\.[a-z]+$/i, "")
  const m = id.match(/^(\d{2}-\d{2}-\d{4})_(\d{2})-(\d{2})-(\d{2})_?(.*)$/)
  if (!m) {
    return { at: "", id, name: id }
  }
  const [, date, hh, mm, ss, rest] = m
  return {
    at: `${date} ${hh}:${mm}:${ss}`,
    id,
    name: rest ? rest.replace(/[-_]+/g, " ") : id,
  }
}

const DEMO_FILES = [
  { file: "06-09-2026_14-32-10_zakaz-taksi-do-aeroporta.md", steps: 4 },
  { file: "06-09-2026_11-05-47_spisok-produktov-v-magazin.md", steps: 7 },
  { file: "05-09-2026_19-48-02_napomnit-pro-vstrechu-v-chetverg.md", steps: 2 },
  { file: "05-09-2026_09-14-33_chek-iz-kafe-i-summa-rashoda.md", steps: 5 },
]

/** Список автоматизаций. Сегодня выдуманный — см. оговорку в шапке файла. */
export function listAutomations(): Automation[] {
  return DEMO_FILES.map(({ file, steps }) => ({
    ...parseAutomationFile(file),
    demo: true,
    file,
    steps,
  }))
}

/** Одна автоматизация по адресному ключу. Пусто — такой нет. */
export function automationById(id: string): Automation | undefined {
  return listAutomations().find((a) => a.id === id)
}

/** Адрес страницы автоматизации. */
export function hrefOfAutomation(lang: string, id: string): string {
  return `/${lang}/automation/${id}`
}
