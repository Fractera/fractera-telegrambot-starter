import { AccountButton } from "./_components/account-button.client"

// ГЛАВНАЯ СТРАНИЦА СЛУЖБЫ — ПУБЛИЧНАЯ (156-1).
//
// 🎯 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-07, ДОСЛОВНО: «создай главную страницу пока без
// какого-либо дизайна, просто напиши там главную страницы Telegram бот, она
// должна быть публичной. Добавляй кнопки для авторизации, которые делают
// доступным всё остальное или закрывают всё остальное».
//
// 🔒 ЭТО СМЕНА АРХИТЕКТУРЫ ВХОДА, А НЕ НОВАЯ СТРАНИЦА. Раньше служба была
// закрыта ЦЕЛИКОМ: любой неузнанный запрос уводился на заглушку, и снаружи не
// существовало ни одной поверхности. Отсюда и вопрос владельца, на который у
// прежнего устройства не было ответа: «куда войти и откуда выйти, если проект
// целиком доступен только архитектору». Теперь ответ есть и он виден: вот
// главная, вот кнопка, всё остальное — за ней.
//
// 🔒 ЧТО НЕ ПОМЕНЯЛОСЬ: своего входа у чата по-прежнему НЕТ. Кнопка ведёт в
// единственную службу `:3001`, кука доменная, и все службы видят человека
// одинаково. Публичной стала одна страница, а не авторизация.
//
// 🛑 ДИЗАЙНА ЗДЕСЬ НЕТ НАМЕРЕННО — прямое слово владельца «пока без какого-либо
// дизайна». Страница обязана работать и говорить правду; вид придёт отдельным
// решением.

export default async function Home({ params }: { params: Promise<{ lang: string }> }) {
  const { lang } = await params

  return (
    <main data-public-home style={{ display: "flex", flexDirection: "column", gap: 16, padding: 24 }}>
      <h1>Главная страница Telegram бот</h1>

      <p>
        Публичная страница службы. Разделы проекта — описание, логи, история автоматизаций,
        настройки, паспорт — доступны после входа с ролью архитектора.
      </p>

      {/* 🔒 ОСТРОВОК, А НЕ СЕРВЕРНАЯ ПРОВЕРКА: страница публичная и статическая по
          природе, а «кто вошёл» — свойство браузера. Спроси мы сессию на сервере,
          страница стала бы динамической для каждого посетителя ради одной строки. */}
      <AccountButton lang={lang} />
    </main>
  )
}
