// Машина может их перечислить, а значит ответить на «что у нас есть про место»
// не открывая ни одного тела записи. Открой словарь — теги станут свободным
// текстом, то есть перестанут быть фильтром и станут вторым описанием.
//
// 🔒 СПИСОК ЖИВЁТ `as const` В КОДЕ, А НЕ В JSON, ПО ПРИЧИНЕ, УЖЕ ОПЛАЧЕННОЙ
// СТОРОЖЕМ `check-registry.mjs`: из него порождаются типы, и опечатка ловится
// проверкой типов, а не глазами. Перенеси его в конфиг — и `plaсe` вместо
// `place` станет валидным значением, которое просто никогда не совпадёт.
//
// 🛑 НУЖЕН ТЕГ, КОТОРОГО ЗДЕСЬ НЕТ, — ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, А НЕ ПРАВКА ПО ХОДУ.
// Добавление тега меняет то, как ищутся ВСЕ записи, а не одна: старые записи
// нового тега не имеют, и первый же поиск по нему вернёт неполный ответ.

export const REGISTRY_TAGS = [
  /** время, сроки, расписание */
  "time",
  /** место, география, адрес */
  "place",
  /** человек: кто он, что предпочитает, как с ним связаться */
  "person",
  /** деньги, суммы, валюты */
  "money",
  /** файлы, фото, голос, видео */
  "media",
  /** содержание самого сообщения */
  "text",
  /** служебное: про саму систему, её состояние и работу */
  "system",
  /** требует обращения наружу — сеть, чужая служба, ключ */
  "external",
] as const

export type RegistryTag = (typeof REGISTRY_TAGS)[number]

export function isRegistryTag(v: unknown): v is RegistryTag {
  return typeof v === "string" && (REGISTRY_TAGS as readonly string[]).includes(v)
}
