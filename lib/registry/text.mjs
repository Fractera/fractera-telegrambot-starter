// 🛑 СЛУЖЕБНЫЕ СЛОВА ВЫБРАСЫВАЮТСЯ, И ЭТО НЕ УКРАШЕНИЕ. ✗ измерено: запрос
// «напомни мне через две минуты» совпал с признаком «когда это случилось» —
// по слову «через» в чужом описании. Одно служебное слово превращает поиск в
// шум, и выглядит это как работающий поиск.

const STEM_LEN = 5;
const MIN_WORD = 3;

const STOP = new Set([
  "или", "если", "как", "что", "это", "для", "при", "над", "под", "про",
  "через", "мне", "меня", "мой", "моя", "мои", "его", "её", "их", "там",
  "тут", "уже", "ещё", "еще", "так", "все", "всё", "был", "была", "было",
  "быть", "есть", "тот", "тогда", "когда", "где", "кто", "чем", "чём",
  "than", "the", "and", "for", "with",
]);

export function words(text) {
  return String(text ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^0-9a-zа-я-]+/g, " ")
    .split(/\s+/)
    .filter((w) => w.length >= MIN_WORD && !STOP.has(w));
}

export function stems(text) {
  return words(text).map((w) => w.slice(0, STEM_LEN));
}
