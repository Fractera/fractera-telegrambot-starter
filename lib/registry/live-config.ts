// 🔒 ЗАЧЕМ ЭТО ВООБЩЕ ВАЖНО: РЕЕСТР — ЭТО ОБЕЩАНИЕ «ЭВОЛЮЦИЯ БЕЗ ПЕРЕСБОРКИ»
