//
// 🔒 ЗАПЕЧЁННЫЙ ИМПОРТ ОСТАЁТСЯ ЗАПАСОМ, А НЕ УДАЛЯЕТСЯ. Файла может не быть
// рядом: другая раскладка, другая среда, чужая машина. Тогда система работает по
// тому, что вошло в сборку, — это хуже свежего, но лучше пустого реестра.
// 🔒 И РОВНО ПОЭТОМУ ИСХОД ЧТЕНИЯ НАЗЫВАЕТСЯ ВСЛУХ (`source`): «читаю с диска» и
// «работаю по запечённому» — разные состояния, и молча слить их значит однажды
// объяснять человеку, почему его правка не подействовала.

export type ConfigSource = "disk" | "baked"

type Cached = { at: number; mtime: number; data: unknown }

const cache = new Map<string, Cached>()

/**
 * Как часто перечитывать, даже если время правки не изменилось.
 *
 * 🔒 `statSync` НА КАЖДЫЙ ВЫЗОВ БЫЛ БЫ ЛИШНИМ: реестр читают десятки раз на один
 * запрос. Полсекунды — это «мгновенно» для человека и «редко» для диска.
 */
const RECHECK_MS = 500

/**
 * Прочитать конфиг реестра.
 *
 * Возвращает разобранный JSON и **источник**: диск или запечённое.
 *
 * 🔒 БИТЫЙ ФАЙЛ — ЭТО ПОВОД ВЗЯТЬ ЗАПЕЧЁННОЕ, А НЕ УПАСТЬ. Реестр правит агент
 * своим редактором; недописанный JSON в момент чтения — обычное дело, и терять
 * из-за него весь разбор нельзя.
 */
export function readLiveConfig<T>(relPath: string, baked: T): { data: T; source: ConfigSource } {
  const full = join(process.cwd(), relPath)
  const now = Date.now()
  const hit = cache.get(relPath)

  if (hit && now - hit.at < RECHECK_MS) {
    return { data: hit.data as T, source: hit.mtime > 0 ? "disk" : "baked" }
  }

  try {
    const mtime = statSync(full).mtimeMs
    if (hit && hit.mtime === mtime) {
      cache.set(relPath, { ...hit, at: now })
      return { data: hit.data as T, source: "disk" }
    }
    const parsed = JSON.parse(readFileSync(full, "utf8")) as T
    cache.set(relPath, { at: now, mtime, data: parsed })
    return { data: parsed, source: "disk" }
  } catch {
    // 🔒 ЗАПАС НЕ КЭШИРУЕТСЯ КАК УСПЕХ: файл может появиться через секунду —
    // например, когда агент дописал правку. Запоминаем `mtime: 0`, чтобы
    // следующая проверка снова пошла на диск.
    cache.set(relPath, { at: now, mtime: 0, data: baked })
    return { data: baked, source: "baked" }
  }
}

/** Откуда сейчас читается конфиг — для экрана и диагностики. */
export function configSource(relPath: string): ConfigSource {
  const hit = cache.get(relPath)
  return hit && hit.mtime > 0 ? "disk" : "baked"
}
