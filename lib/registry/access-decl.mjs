/**
 * Схема инструмента MCP, порождённая из объявления.
 *
 * 🔒 ПОРОЖДАЕТСЯ, А НЕ ПИШЕТСЯ РЯДОМ. Схема, написанная руками возле объявления,
 * разойдётся с ним на первой правке параметра — тот же закон, что у чисел в
 * инструкциях, оплаченный в проекте четырежды.
 */
// 🛑 НАШ ПСЕВДОТИП ПЕРЕВОДИТСЯ В JSON SCHEMA, А НЕ УЕЗЖАЕТ В НЕЁ КАК ЕСТЬ.
//
// ✗ ОПЛАЧЕНО ЖИВЬЁМ 2026-09-09, И ОТКАЗ БЫЛ НЕМЫМ ЦЕЛЫЕ СУТКИ. Здесь стояло
// `type: p.type`, и наш внутренний тип `value` уезжал в схему инструмента.
// `value` — не тип JSON Schema, и API Anthropic отвергал ВЕСЬ инструмент:
//   "schema/properties/what/type must be equal to one of the allowed values".
// Привратник молча исключал `memory_write` и `memory_mutate` из списка каждой
// сессии — при том, что MCP-сервер их объявлял, дверь отвечала `ok:true`, а
// `tools/list` показывал все двенадцать. **Инструмент был построен, объявлен и
// недостижим.**
//
// 🔒 ПОЧЕМУ ЭТОГО НЕ ВИДЕЛ НИ ОДИН ПРИБОР: все они спрашивали НАС — сервер и
// дверь, — а отвергал схему ТРЕТИЙ, между агентом и нами. Правило шире случая:
// **у инструмента для модели есть третья сторона, и её ответ надо измерять
// отдельно.** Здесь она отвечает строкой «Unavailable MCP Tools» в журнале сессии.
//
// 🔒 `value` — строка ИЛИ объект одного уровня (160-3), поэтому список из двух
// простых типов, а не один. Метасхема JSON Schema это разрешает.
const JSON_SCHEMA_TYPE = {
  array: "array",
  boolean: "boolean",
  integer: "integer",
  number: "number",
  object: "object",
  string: "string",
  value: ["string", "object"],
};

export function mcpToolFrom(decl) {
  const properties = {};
  const required = [];
  for (const p of decl.params) {
    const type = JSON_SCHEMA_TYPE[p.type];
    if (!type) {
      // 🔒 НЕИЗВЕСТНЫЙ ТИП — ОТКАЗ ЗДЕСЬ, А НЕ МОЛЧАЛИВОЕ ИСКЛЮЧЕНИЕ ТАМ.
      // Промолчав, мы вернули бы ровно тот дефект, ради которого написан этот
      // перевод: инструмент пропадает у агента, а у нас всё зелено.
      throw new Error(
        `mcpToolFrom: у параметра \`${p.name}\` метода \`${decl.name}\` тип ` +
          `\`${p.type}\`, которого нет в JSON_SCHEMA_TYPE. Добавь перевод.`,
      );
    }
    properties[p.name] = { description: p.about, type };
    if (p.required) {
      required.push(p.name);
    }
  }
  return {
    description: `${decl.title}. ${decl.about} Возвращает: ${decl.returns}. Промах: ${decl.onMiss}.`,
    inputSchema: { properties, required, type: "object" },
    name: decl.name,
  };
}

/** Проверка параметров на границе: чужое и лишнее не проходит. */
export function validateArgs(decl, args) {
  const a = args && typeof args === "object" ? args : {};
  const out = {};
  const problems = [];
  for (const p of decl.params) {
    const v = a[p.name];
    if (v === undefined || v === null) {
      if (p.required) {
        problems.push(`нет обязательного параметра \`${p.name}\` — ${p.about}`);
      }
      continue;
    }
    // 🔒 ТИП `value` — СТРОКА ИЛИ ОБЪЕКТ ОДНОГО УРОВНЯ (160-3). Глубина 1 хранится
    // объектом; проверка «только строка» отвергала бы его на входе, и сторож
    // глубины никогда бы не увидел того, что должен сторожить.
    // ✗ НАЙДЕНО ПРИБОРОМ 160: объектные значения давали `bad-args` ДО сторожа —
    // то есть запрет срабатывал раньше правила и по другой причине.
    // 🛑 ВЛОЖЕННОСТЬ ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ НАМЕРЕННО: это дело сторожа, у которого
    // есть причина отказа словами. Две проверки одного и того же разошлись бы.
    // 🔒 МАССИВ ПРОПУСКАЕТСЯ СЮДА НАМЕРЕННО, ЧТОБЫ ЕГО ОТВЕРГ СТОРОЖ.
    // ✗ найдено прибором 160: отвергнутый здесь массив давал «параметр `value`
    // должен быть value, а пришло object» — сообщение, из которого человеку нечего
    // понять. Сторож говорит по делу: «список сущностей пишется по одной строке».
    // 🛑 ПРАВИЛО ШИРЕ СЛУЧАЯ: проверка формы не должна перехватывать то, для чего
    // есть проверка смысла, — иначе человек получает худший из двух ответов.
    // 🔒 `boolean` ДОБАВЛЕН 2026-09-08 (162-4), И ЭТО ПОЧИНКА ЛОВУШКИ, А НЕ НОВЫЙ
    // ТИП. Неизвестный тип падал в `else` и требовал СТРОКУ: объявить параметр
    // `boolean` было можно, а прислать `true` — нельзя, и отказ звучал как
    // «должен быть boolean, а пришло boolean». ✗ поймано прибором 162-4 в тот же
    // час: разрешение на дорогой поиск не проходило границу вовсе.
    // 🛑 ПРАВИЛО ШИРЕ СЛУЧАЯ: молчаливое приведение НЕИЗВЕСТНОГО к строке — это
    // проверка, которая соглашается на всё, чего не понимает.
    const ok =
      p.type === "value"
        ? typeof v === "string" || (typeof v === "object" && v !== null)
        : p.type === "number"
          ? typeof v === "number" && Number.isFinite(v)
          : p.type === "array"
            ? Array.isArray(v)
            : p.type === "boolean"
              ? typeof v === "boolean"
              : typeof v === "string";
    if (!ok) {
      problems.push(`параметр \`${p.name}\` должен быть ${p.type}, а пришло ${typeof v}`);
      continue;
    }
    out[p.name] = v;
  }
  // 🛑 ЛИШНИЙ ПАРАМЕТР — ОТКАЗ, А НЕ МОЛЧАЛИВОЕ ИГНОРИРОВАНИЕ. Опечатка в имени
  // («subj» вместо «subject») иначе выглядит как честный ответ по всем данным,
  // хотя сужение просто не применилось.
  for (const name of Object.keys(a)) {
    if (!decl.params.some(p => p.name === name)) {
      problems.push(`неизвестный параметр \`${name}\``);
    }
  }

  // ── СВЯЗАННЫЕ ПАРАМЕТРЫ: `requires` И `oneOf` (162-6) ──────────────────────
  //
  // 🔒 ПРАВИЛО КОМБИНАЦИИ ЖИВЁТ В ОБЪЯВЛЕНИИ, А НЕ ВТОРОЙ КОПИЕЙ В КОДЕ. Условие
  // «блок дообучения требует подтверждения» до этого стояло в двух местах: текстом
  // в описании параметра и проверкой внутри ящика. Две копии расходятся на первой
  // правке, и слабейшая становится настоящей границей.
  for (const p of decl.params) {
    if (out[p.name] === undefined || !Array.isArray(p.requires)) continue;
    for (const need of p.requires) {
      if (out[need] === undefined || out[need] === false) {
        problems.push(`параметр \`${p.name}\` требует \`${need}\` — ${p.about}`);
      }
    }
  }
  // 🔒 ВЗАИМОИСКЛЮЧАЮЩИЕ ПАРАМЕТРЫ ОТВЕРГАЮТСЯ НА ГРАНИЦЕ, А НЕ РАЗБИРАЮТСЯ
  // ВНУТРИ. Прислав и ключ, и якоря, зовущий сам не знает, о ком его запись;
  // выбрать за него значит записать не туда молча.
  if (Array.isArray(decl.oneOf)) {
    const given = decl.oneOf.filter(name => out[name] !== undefined);
    if (given.length > 1) {
      problems.push(
        `назови ОДНО из: ${decl.oneOf.map(n => "`" + n + "`").join(", ")} — пришло сразу ${given.length}`,
      );
    }
  }
  return problems.length > 0 ? { ok: false, problems } : { ok: true, args: out };
}
