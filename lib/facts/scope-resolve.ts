import { scopeKey } from "./scope"
import type { Fact } from "./types"

// ОХВАТ СЧИТАЕТСЯ ОДИН РАЗ НА СООБЩЕНИЕ И НАСЛЕДУЕТСЯ ЕГО ФАКТАМИ (141-3).
//
// 🔒 «ГДЕ МЫ» — СВОЙСТВО РАЗГОВОРА, А НЕ ПРИЗНАКА. Из одного сообщения могут
// сработать десять признаков, и все они верны в одном и том же месте. Спроси мы
// охват у каждого — десять одинаковых ответов ценой десяти обращений, а при
// участии модели ещё и ценой денег.
//
// 🛑 ЖИВОГО РАЗБОРА СООБЩЕНИЯ В СЛУЖБЕ ПОКА НЕТ (§1 паспорта — сепарация не
// построена). Здесь строится узел, который разбор позовёт: он принимает
// сработавшие признаки и ИСТОЧНИКИ значений, а откуда источники берут ответ,
// его не касается. Названо вслух, чтобы «готово» не читалось как «работает в
// проде».

/**
 * Источник значения измерения охвата.
 *
 * 🔒 ПОРЯДОК ИСТОЧНИКОВ — ЭТО ПОРЯДОК ДОВЕРИЯ, А НЕ УДОБСТВА. Сказанное сейчас
 * сильнее сказанного вчера; вчерашнее сильнее, чем ничего. Первый ответивший
 * побеждает, остальных не спрашивают.
 */
export type ScopeSource = {
  /** Имя для отчёта: по нему человек поймёт, откуда взялось значение. */
  name: string
  /** Пусто — «не знаю»: это законный ответ, а не отказ. */
  lookup: (dimension: string) => string | undefined | Promise<string | undefined>
}

export type ScopeResolution = {
  /** Готовый ключ для колонки `scope_key`. Пусто — охват неизвестен. */
  key: string
  /** Что удалось узнать: измерение → значение. */
  pairs: Record<string, string>
  /** Каких измерений не хватило. Именно их спрашивают у человека (141-7). */
  missing: string[]
  /** Кто ответил на каждое измерение — для строки в ленте и для отладки. */
  answeredBy: Record<string, string>
  /** Сколько раз спросили источники. Прибор смотрит сюда. */
  lookups: number
}

/**
 * Какие измерения нужны этому сообщению — объединение по сработавшим признакам.
 *
 * 🔒 ОБЪЕДИНЕНИЕ, А НЕ СПИСОК НА ПРИЗНАК. Два признака, зависящие от города,
 * дают ОДНО измерение: спрашивать дважды нечего.
 * 🔒 ПОРЯДОК УСТОЙЧИВЫЙ (сортировка), потому что от него зависит порядок
 * обращений к источникам, а его человек видит в отчёте.
 */
export function neededDimensions(facts: Fact[]): string[] {
  const set = new Set<string>()
  for (const f of facts) for (const k of f.scope ?? []) set.add(k)
  return [...set].sort()
}

/**
 * Разрешить охват сообщения.
 *
 * 🔒 КАЖДОЕ ИЗМЕРЕНИЕ СПРАШИВАЕТСЯ РОВНО ОДИН РАЗ, И ЭТО ГЛАВНОЕ СВОЙСТВО УЗЛА.
 * Не «по разу на признак», а по разу на измерение — и первый ответивший источник
 * закрывает вопрос.
 *
 * 🔒 НЕДОСТАЮЩЕЕ НЕ ДЕЛАЕТ РАБОТУ НЕУДАЧНОЙ. Оно попадает в `missing`, и это
 * вход для вопроса человеку (141-7). Отказ здесь означал бы, что сообщение с
 * неизвестным городом нельзя разобрать вовсе, — а его разобрать можно, просто
 * факт останется беспризорным.
 */
export async function resolveScope(
  facts: Fact[],
  sources: ScopeSource[],
): Promise<ScopeResolution> {
  const dims = neededDimensions(facts)
  const pairs: Record<string, string> = {}
  const answeredBy: Record<string, string> = {}
  const missing: string[] = []
  let lookups = 0

  for (const dim of dims) {
    let value: string | undefined
    for (const source of sources) {
      lookups++
      value = await source.lookup(dim)
      if (value) {
        answeredBy[dim] = source.name
        break
      }
    }
    if (value) pairs[dim] = value
    else missing.push(dim)
  }

  // 🔒 КЛЮЧ СТРОИТСЯ, ТОЛЬКО ЕСЛИ ИЗВЕСТНО ВСЁ ОБЪЯВЛЕННОЕ. Половина охвата —
  // это другой охват, шире объявленного: тот же закон, что в `scopeKey()`.
  const key = missing.length === 0 && dims.length > 0 ? scopeKey(pairs) : ""
  return { key, pairs, missing, answeredBy, lookups }
}

/**
 * Раздать один охват всем фактам сообщения.
 *
 * 🔒 НАСЛЕДУЮТ ВСЕ, А НЕ ТОЛЬКО ЗАВИСИМЫЕ, И ЭТО РЕШЕНИЕ, А НЕ НЕБРЕЖНОСТЬ.
 * Факт, не объявивший зависимости, всё равно случился ГДЕ-ТО; знание об этом
 * дешёвое и понадобится, как только человек объявит зависимость задним числом.
 * Обратное — стереть охват у необъявивших — потребовало бы разбирать прошлое
 * заново, а разобрать его нечем: где был человек в ту минуту, знает только он.
 */
export function applyScope<T extends { scopeKey?: string }>(rows: T[], key: string): T[] {
  return rows.map(r => ({ ...r, scopeKey: key }))
}
