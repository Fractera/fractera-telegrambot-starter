// берутся записи. Ровно поэтому переезд хранилища из базы в файл стоил правки
// одного `store.ts`, а не двадцати файлов. Убрать посредника значило бы
// разложить знание о хранилище по всем потребителям.

/**
 * Весь реестр.
 *
 * 🔒 ПОРЯДОК — ТОТ, ЧТО В ФАЙЛЕ, И ЭТО НЕ МЕЛОЧЬ. На экране человек читает
 * сверху вниз; порядок записей в конфиге и есть порядок, который он увидит.
 * Пересортировать здесь значило бы отнять у автора файла управление тем, что
 * читается первым.
 *
 * 🔒 ФУНКЦИЯ НЕ АСИНХРОННАЯ. Пока записи лежали в базе, у чтения был отказ:
 * слой данных мог не ответить. Файл входит в сборку — отказу взяться неоткуда,
 * и `async` обещал бы ожидание, которого нет.
 */
export function allFacts(): Fact[] {
  return storedFacts()
}

/** Только те, что участвуют в разборе: выключенные не участвуют. */
export function activeFacts(): Fact[] {
  return allFacts().filter(f => f.enabled)
}

