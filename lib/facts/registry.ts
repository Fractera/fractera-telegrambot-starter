import { builtinFacts } from "./builtin"
import { storedFacts } from "./store"
import type { Fact } from "./types"

// РЕЕСТР ЦЕЛИКОМ — встроенные плюс описанные человеком (81-2).
//
// 🔒 ВСТРОЕННЫЕ НЕ ХРАНЯТСЯ НИГДЕ, И ЭТО НЕ ЭКОНОМИЯ. Они ПОРОЖДАЮТСЯ из кода
// (81-1), потому что описывают то, что система делает по устройству. Запиши их
// строками — и появится вторая правда, которая разойдётся с первой на первом же
// изменении кода, причём молча: запись останется прежней, а поведение изменится.
//
// 🔒 ЭТОТ ФАЙЛ — ЕДИНСТВЕННАЯ ДВЕРЬ К РЕЕСТРУ ДЛЯ ОСТАЛЬНОГО КОДА. `builtin.ts`,
// `detail.ts`, `ensure.ts`, `derived.ts` и экран зовут его и не знают, откуда
// берутся записи. Ровно поэтому переезд хранилища из базы в файл (2026-09-06)
// стоил правки одного файла, а не двадцати.

/**
 * Весь реестр: сначала встроенные, затем описанные.
 *
 * 🔒 ПОРЯДОК ЗНАЧИМ. Встроенные описывают устройство и потому идут первыми; на
 * экране человек читает сверху вниз и должен сперва увидеть, что уже умеет
 * система, а потом — что к этому добавлено.
 *
 * 🔒 ФУНКЦИЯ БОЛЬШЕ НЕ АСИНХРОННАЯ, И ЭТО НЕ КОСМЕТИКА. Пока записи лежали в
 * базе, у чтения был отказ: слой данных мог не ответить, и реестр честно
 * вырождался во встроенные. Файл входит в сборку — отказу взяться неоткуда, и
 * `async` обещал бы ожидание, которого нет.
 */
export function allFacts(): Fact[] {
  return [...builtinFacts(), ...storedFacts()]
}

/** Только те, что участвуют в разборе: выключенные не участвуют. */
export function activeFacts(): Fact[] {
  return allFacts().filter(f => f.enabled)
}

