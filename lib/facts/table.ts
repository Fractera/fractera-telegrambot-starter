// ИМЯ И ФОРМА ТАБЛИЦЫ ПРИЗНАКА — одно место на весь проект (81-2).
//
// 🔒 ЕДИНЫЙ СТАНДАРТ БЕЗ ИСКЛЮЧЕНИЙ — решение владельца 2026-09-01, дословно:
// «стандарт таблицы должен быть у всех кроме первого пункта… то что у нас есть
// стандартные таблицы в которой зафиксировано хардкодом как раз таки делает
// невозможность создания единого паттерна, что является архитектурным
// нарушением… чтобы у модели не было иллюзии что можно делать так и так, а
// значит как угодно».
//
// Довод принят как более сильный, чем прежний агентский. Агент возражал
// экономией — «не переписывать работающее»; владелец возразил архитектурой: два
// способа хранения есть отсутствие способа. Выбор без критерия читается как
// разрешение выбирать по настроению, и следующая сессия положит признак туда,
// где ей будет удобнее в тот день.
//
// 🔒 ИСКЛЮЧЕНИЕ РОВНО ОДНО, И ОНО ПО ПРИРОДЕ. Связь сообщений — не факт О
// сообщении, а отношение МЕЖДУ двумя: у неё нет значения, есть источник и цель.
// Она живёт в `tgdesk_messages.bundle` и существует до всякого реестра.

/** Признак, у которого своей таблицы нет и не будет. */
export const FACT_WITHOUT_TABLE = "field.link"

/**
 * 🛑 БЕЛЫЙ СПИСОК СИМВОЛОВ — ЗАЩИТА, А НЕ ОПРЯТНОСТЬ.
 *
 * Ключ признака рождается из СВОБОДНОГО ОПИСАНИЯ человека, пропущенного через
 * модель. Попав в `CREATE TABLE` без проверки, он перестаёт быть именем и
 * становится куском SQL. Здесь нет места вежливой нормализации «на всякий
 * случай»: имя либо целиком состоит из разрешённого, либо отвергается.
 */
// 🔒 ДЕФИС РАЗРЕШЁН ВНУТРИ СЕГМЕНТА, НО НЕ ПО КРАЯМ (158-5б).
// ✗ НАЙДЕНО ЖИВЫМ ЗАМЕРОМ 2026-09-08: `registry_remember` отказал ключу
// `person.address-form` со словами «из ключа не собирается имя таблицы».
// А в реестре С САМОГО НАЧАЛА живут `initiator.telegram-user`,
// `initiator.chat-user`, `material.calendar-date`, и README обещает дефис
// прямым текстом. Расхождение было НЕВИДИМО ровно потому, что все три —
// встроенные: их значения лежат колонками чужих таблиц, и своё имя таблицы
// им никогда не собиралось.
// 🛑 СТРОГОСТЬ НЕ ОСЛАБЛЕНА: дефис не может стоять первым или последним в
// сегменте и не может идти подряд. `--` в имени таблицы — это начало
// SQL-комментария, и пропустить его значило бы вернуть ровно ту дыру, от
// которой белый список и заведён.
const ALLOWED = /^[a-z][a-z0-9]*(-[a-z0-9]+)*(\.[a-z][a-z0-9]*(-[a-z0-9]+)*)*$/
const MAX_KEY = 48

/** Имя таблицы значений признака. Пусто — имя недопустимо, таблицу создавать нельзя. */
export function factTableName(key: string): string {
  if (typeof key !== "string") return ""
  const k = key.trim().toLowerCase()
  if (!k || k.length > MAX_KEY) return ""
  if (!ALLOWED.test(k)) return ""
  // Точка — разделитель уровня в ключе (`field.money`); в имени таблицы она
  // становится подчёркиванием. Приставка обязательна: по ней таблицы признаков
  // отличают от всех прочих одним взглядом и одним запросом.
  // Дефис внутри сегмента — тоже разделитель слов, и в имени таблицы он
  // становится подчёркиванием: `person.address-form` → `fact_person_address_form`.
  return `fact_${k.replace(/[.-]/g, "_")}`
}

/**
 * Простое машинное имя без уровней: слот значения, статус жизненного цикла.
 *
 * 🔒 ТА ЖЕ ЗАЩИТА, ЧТО У ИМЕНИ ТАБЛИЦЫ, И ТОТ ЖЕ БЕЛЫЙ СПИСОК — НЕ ВТОРОЙ (83-1).
 * `slot` и статус приезжают из свободного описания человека через модель ровно
 * так же, как ключ признака, и попадают в значения колонок и в условия запросов.
 * Заведи я рядом вторую, «попроще», нормализацию — она разошлась бы с этой на
 * первом же ужесточении, и слабейшая стала бы настоящей границей.
 *
 * Отличие от `factTableName` ровно одно: точки здесь не бывает — уровней у слота
 * нет. Пусто — имя недопустимо, и его не сохраняют.
 */
export function factIdentifier(name: string): string {
  if (typeof name !== "string") return ""
  const n = name.trim().toLowerCase()
  if (!n || n.length > MAX_KEY) return ""
  return /^[a-z][a-z0-9]*$/.test(n) ? n : ""
}

/**
 * ФОРМА ТАБЛИЦЫ — ОДНА НА ВСЕ ПРИЗНАКИ, и в этом весь смысл стандарта.
 *
 * 🔒 ОДНА ФОРМА ОЗНАЧАЕТ НОЛЬ КОДА НА НОВЫЙ ПРИЗНАК: один читатель, один
 * писатель. Признак, добавленный человеком в понедельник, обслуживается тем же
 * кодом, что встроенный.
 *
 * 🔒 ПОЧЕМУ ТРИ КОЛОНКИ ЗНАЧЕНИЯ, А НЕ ОДНА. Сумма должна складываться и
 * сравниваться — для этого нужно число; координата и вложенные поля не
 * укладываются в строку без потерь. Класть всё в текст значит однажды считать
 * расходы строковым сравнением.
 *
 * 🔒 `source` И `confidence` — ТО, ЧЕГО КОЛОНКА НЕ ЗНАЕТ НИКОГДА. Значение,
 * извлечённое моделью, пришедшее геометкой, склеенное из соседнего сообщения и
 * названное человеком в ответ на вопрос, — это четыре разные степени доверия, и
 * различать их придётся ровно в тот день, когда два источника разойдутся.
 */
export function factTableSql(table: string): string {
  return `
    CREATE TABLE IF NOT EXISTS ${table} (
      id         INTEGER PRIMARY KEY AUTOINCREMENT,
      -- 🔒 СООБЩЕНИЕ НЕОБЯЗАТЕЛЬНО, И ЭТО ИСПРАВЛЕНИЕ ОБРАЗЦА (158-5б).
      -- ✗ ОПЛАЧЕНО ЖИВЫМ ЗАМЕРОМ 2026-09-08: NOT NULL constraint failed на
      -- fact_person_name.message_id. Образец предполагал, что КАЖДЫЙ факт
      -- добыт из сообщения. Факт о человеке рождается ещё двумя путями: агент
      -- запомнил сказанное в разговоре (registry_remember) и человек поправил
      -- значение руками на экране. У обоих сообщения нет и быть не может.
      -- 🛑 ПОДСТАВИТЬ СЮДА ПУСТУЮ СТРОКУ РАДИ NOT NULL БЫЛО БЫ ХУЖЕ ОТКАЗА:
      -- это выдуманный адрес сообщения, по которому потом пойдут искать.
      message_id INTEGER,
      value_text TEXT,
      value_num  REAL,
      value_json TEXT,
      source     TEXT NOT NULL DEFAULT 'model',
      confidence REAL,
      -- ── ВТОРОЙ СЛОЙ (83-2). Три колонки у ВСЕХ признаков, а не у тех, кому
      -- нужны: единый стандарт без исключений — действующее решение владельца,
      -- и «часть так, часть иначе» есть отсутствие правила.
      --
      -- Какое из нескольких значений признака это. Пусто у обычного признака.
      slot        TEXT,
      -- Чей это факт: self, ключ человека, либо пусто у ничьего.
      subject_key TEXT,
      -- Состояние на момент строки. Переход пишется НОВОЙ строкой, а не правкой:
      -- вопрос «когда задание стало проверенным» без истории ответа не имеет.
      status      TEXT,
      -- Где этот факт верен: geo.city=madrid|lang=ru (141-2). Пусто — «не знаю
      -- где», а НЕ «везде»: беспризорный факт показывается названным.
      scope_key   TEXT,
      -- ── ЧЕТВЁРТЫЙ СЛОЙ (161-2): СКАЗАНО ИЛИ ВЫВЕДЕНО ──────────────────────
      --
      -- 🔒 РАЗНИЦА МЕЖДУ УТВЕРЖДЕНИЕМ И ПРЕДПОЛОЖЕНИЕМ ХРАНИТСЯ, А НЕ ДЕРЖИТСЯ
      -- НА ДИСЦИПЛИНЕ МОДЕЛИ (§8.2 стандарта памяти). «fact» — человек сказал
      -- это прямо; «guess» — система вывела сама. Пусто у строк, записанных до
      -- этого слоя: молчание честнее задним числом присвоенной уверенности.
      --
      -- 🛑 ОБРАТНЫХ КАВЫЧЕК В ЭТОМ КОММЕНТАРИИ НЕТ НАМЕРЕННО: он живёт ВНУТРИ
      -- шаблонной строки, и первая же такая кавычка закрывает её — форма таблицы
      -- рвётся на середине, а компилятор жалуется на объявление модулей, то есть
      -- уводит от причины. ✗ поймано проверкой типов в 161-2, до отправки.
      --
      -- 🛑 ПОЧЕМУ ЭТО НЕ ВЫВОДИТСЯ ИЗ «source». Соблазн велик: «раз пришло от
      -- модели — предположение». Но модель извлекает и прямо сказанное («меня
      -- зовут Рома»), а человек на экране может записать догадку о себе. Вывод
      -- ошибается в обе стороны, и обе ошибки молчаливые.
      claim       TEXT,
      -- На чём стоит предположение. У «guess» обязательно — иначе догадка
      -- неотличима от знания ровно тогда, когда её захотят проверить.
      basis       TEXT,
      created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
    );
    CREATE INDEX IF NOT EXISTS ${table}_message ON ${table} (message_id);
    -- Накопление спрашивают по хозяину и времени: «сколько Я за неделю».
    CREATE INDEX IF NOT EXISTS ${table}_subject ON ${table} (subject_key, created_at);
    -- Чтение сужается по охвату: «что я знаю про такси ЗДЕСЬ».
    CREATE INDEX IF NOT EXISTS ${table}_scope ON ${table} (scope_key, created_at);
  `
}

/**
 * Лестница колонок для таблиц, СОЗДАННЫХ РАНЬШЕ (83-2).
 *
 * 🔒 `CREATE TABLE IF NOT EXISTS` НЕ ДОБАВЛЯЕТ КОЛОНКУ. На машине, где таблица
 * уже есть — а это всякая машина, кроме чистой, — он молча не делает ничего.
 * Двадцать четыре таблицы признаков созданы шагом 81-2 и о втором слое не знают.
 *
 * ✗ ОПЛАЧЕНО В ПРОЕКТЕ ДВАЖДЫ: колонка, объявленная в схеме, на сервере не
 * появилась (2026-08-17), а лестница, жившая только на локальном пути, перестала
 * исполняться вовсе (2026-08-18).
 *
 * 🔒 ЛЕСТНИЦА ЖИВЁТ ЗДЕСЬ, РЯДОМ С ОБРАЗЦОМ ФОРМЫ. Положи я её в `ensure.ts` —
 * форма и её починка оказались бы в разных файлах и разошлись бы при следующей
 * колонке: тот, кто правит образец, не увидит лестницу.
 */
// 🔒 ПОДНЯТАЯ ЛЕСТНИЦЕЙ ТАБЛИЦА И ВНОВЬ СОЗДАННАЯ ИМЕЮТ ОДИН НАБОР КОЛОНОК, НО
// РАЗНЫЙ ИХ ПОРЯДОК, И ЭТО ЗАКОННО. `ALTER TABLE ADD COLUMN` дописывает в конец,
// поэтому у старой таблицы выходит `… created_at slot subject_key status`, а у
// новой `… confidence slot subject_key status created_at`.
//
// 🔒 БЕЗРАЗЛИЧНО ЭТО РОВНО ПОТОМУ, ЧТО МЫ НИКОГДА НЕ ОБРАЩАЕМСЯ ПОЗИЦИОННО, и
// это ИЗМЕРЕНО, а не предположено (2026-09-02): `SELECT *` по `lib/facts/` —
// ноль файлов, все `INSERT` называют колонки поимённо.
// 🛑 ОТСЮДА ЗАПРЕТ, КОТОРЫЙ РАНЬШЕ БЫЛ ПРИВЫЧКОЙ: `SELECT *` и `INSERT` без
// списка колонок по таблицам признаков запрещены. Они работают на чистой машине
// и дают перепутанные значения на обновлённой — то есть ломаются ТОЛЬКО у того,
// у кого система уже поработала.
//
// 🔒 СВЕРКА СТАНДАРТА СРАВНИВАЕТ НАБОР, А НЕ ПОСЛЕДОВАТЕЛЬНОСТЬ — по той же
// причине. Сравнивай она порядок, каждая поднятая лестницей таблица объявлялась
// бы нестандартной, и отчёт кричал бы о двадцати четырёх исправных таблицах.
// 🔒 ЧЕТВЁРТЫЙ СЛОЙ ДОПИСАН ЗДЕСЬ ТОЙ ЖЕ ПРАВКОЙ, ЧТО И В ОБРАЗЦЕ ВЫШЕ (161-2).
// Колонка, объявленная только в форме, не появится ни на одной из уже созданных
// таблиц — а созданы они все, кроме как на чистой машине. Закон «КОЛОНКА — НЕ
// ТАБЛИЦА» оплачен в проекте трижды, и третий раз — позавчера.
export const FACT_TABLE_LATE_COLUMNS = ["slot", "subject_key", "status", "scope_key", "claim", "basis"] as const

export function factTableAlters(table: string): string[] {
  return FACT_TABLE_LATE_COLUMNS.map(c => `ALTER TABLE ${table} ADD COLUMN ${c} TEXT`)
}

/** Колонки образца — по ним сверяется, что таблица построена стандартно. */
export const FACT_TABLE_COLUMNS = [
  "id",
  "message_id",
  "value_text",
  "value_num",
  "value_json",
  "source",
  "confidence",
  // ── Второй слой (83-2). Число колонок правится ВМЕСТЕ с образцом выше:
  // список, разошедшийся с формой, объявит исправные таблицы нестандартными —
  // ровно то, что уже случилось в 81-2 дважды за один подшаг.
  "slot",
  "subject_key",
  "status",
  // ── Третий слой (141-2): где факт верен.
  "scope_key",
  // ── Четвёртый слой (161-2): сказано или выведено, и на чём стоит вывод.
  "claim",
  "basis",
  "created_at",
] as const

/** Признаку положена своя таблица? Ложь — только у отношения между сообщениями. */
export function needsTable(fact: Pick<Fact, "key">): boolean {
  return fact.key !== FACT_WITHOUT_TABLE
}
