// КЛЮЧ ОХВАТА — ТРЕТИЙ СЛОЙ РЕЕСТРА, ЕГО ХРАНИМАЯ ЧАСТЬ (141-2).
//
// 🔒 ЭТО ЧАСТЬ КЛЮЧА ПОИСКА, А НЕ ПОДПИСЬ К ФАКТУ. Значение уезжает и в колонку,
// и в условие запроса: «покажи заметки для Мадрида» превращается в сравнение
// строк. Отсюда всё, что ниже, — строгость не ради красоты, а ради того, чтобы
// две записи об одном месте совпали, а о разных — нет.
//
// 🔒 СОБИРАЕТСЯ БЕЛЫМ СПИСКОМ, КАК ИМЯ ТАБЛИЦЫ. Значения приезжают из свободных
// слов человека через модель; попав в условие запроса без проверки, они
// перестают быть значением и становятся SQL. Тот же приём, что у `factTableName`.

/** Разрешено в собранном ключе: латиница, цифры, дефис — и разделители. */
const ALLOWED_VALUE = /^[a-z0-9-]+$/
const MAX_PART = 64
const MAX_KEY = 256

/**
 * Кириллица → латиница ТАБЛИЦЕЙ, а не догадкой.
 *
 * 🔒 БЕЗ ПЕРЕВОДА НИ ОДНО РУССКОЕ НАЗВАНИЕ НЕ ПОЛУЧИЛО БЫ КЛЮЧА ВОВСЕ: белый
 * список кириллицу не пропускает, и «Мадрид» дал бы пустую строку — то есть
 * «охват неизвестен» там, где человек его назвал.
 * 🔒 ТАБЛИЦА, А НЕ БИБЛИОТЕКА: правила транслитерации у библиотек разные, и смена
 * версии переименовала бы уже записанные ключи — прошлые факты перестали бы
 * находиться, молча.
 */
const CYRILLIC: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
  и: "i", й: "i", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
  с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch",
  ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
}

/**
 * Одно значение — в часть ключа.
 *
 * Пустая строка значит «значение непригодно»: молчаливая подстановка чего-то
 * похожего связала бы разные места одним ключом.
 */
export function scopeValue(raw: unknown): string {
  if (typeof raw !== "string") return ""
  const low = raw.trim().toLowerCase()
  if (!low) return ""

  let out = ""
  for (const ch of low) {
    if (ch in CYRILLIC) out += CYRILLIC[ch]
    else if (/[a-z0-9]/.test(ch)) out += ch
    // Пробел и разделители склеиваются в дефис; всё прочее отбрасывается —
    // кавычка, точка с запятой и скобка в значении не значат ничего полезного.
    else if (/[\s_./-]/.test(ch)) out += "-"
  }
  out = out.replace(/-+/g, "-").replace(/^-|-$/g, "")
  if (!out || out.length > MAX_PART || !ALLOWED_VALUE.test(out)) return ""
  return out
}

/**
 * Собрать ключ охвата из пар «ключ признака → значение».
 *
 * 🔒 ПАРЫ СОРТИРУЮТСЯ ПО ИМЕНИ, И ЭТО НЕ КОСМЕТИКА. Один и тот же охват,
 * собранный в разном порядке, дал бы две разные строки — и факты об одном месте
 * перестали бы находиться друг другом.
 *
 * 🔒 ОДНА НЕПРИГОДНАЯ ПАРА ПОРТИТ ВЕСЬ КЛЮЧ, А НЕ ВЫБРАСЫВАЕТСЯ. Ключ из двух
 * измерений вместо трёх — это ДРУГОЙ охват: он шире объявленного и потому лжив.
 * Пустой результат честнее: он читается как «охват неизвестен».
 *
 * 🔒 ИМЯ ИЗМЕРЕНИЯ ПРОХОДИТ ТУ ЖЕ ПРОВЕРКУ, ЧТО ЗНАЧЕНИЕ. Оно приезжает из
 * реестра, но реестр правит агент — а файл, который правит агент, проверяется
 * так же, как пришедшее снаружи.
 */
export function scopeKey(pairs: Record<string, unknown>): string {
  const names = Object.keys(pairs).sort()
  const parts: string[] = []
  for (const name of names) {
    const dim = scopeValue(name)
    const value = scopeValue(pairs[name])
    if (!dim || !value) return ""
    parts.push(`${dim}=${value}`)
  }
  const key = parts.join("|")
  return key.length > MAX_KEY ? "" : key
}

/**
 * Пустой охват — законное состояние, и у него есть имя.
 *
 * 🔒 «НЕ ЗНАЮ ГДЕ» ≠ «ВЕЗДЕ». Беспризорный факт показывается названным, а не
 * подмешивается к охваченным: молчаливое повышение до универсального и есть тот
 * дефект, ради которого заведён третий слой.
 */
export function isUnscoped(key: string): boolean {
  return key === ""
}

/**
 * Колонка охвата — четвёртая в лестнице поздних колонок.
 *
 * 🔒 ПРОВЕРКА ЖИВЁТ РЯДОМ С ОБЪЯВЛЕНИЕМ: если кто-то уберёт `scope_key` из
 * лестницы, отказ случится здесь и сразу, а не через неделю пустой выдачей.
 */
export const SCOPE_COLUMN = "scope_key"

export function scopeColumnDeclared(): boolean {
  return (FACT_TABLE_LATE_COLUMNS as readonly string[]).includes(SCOPE_COLUMN)
}
