//
// 🎯 ТРЕБОВАНИЕ ВЛАДЕЛЬЦА, ДОСЛОВНО: «прежде чем мы продолжим, нужно чётко
// установить правила сторожа: не пропускать в личную таблицу данные с глубиной
// больше единицы».
//
// 🔒 ГЛУБИНА СЧИТАЕТСЯ ОТ КОРНЯ РЁБРАМИ. Корень — `self`. Ноль — атрибут самого
// человека («имя»). Один — сущность с прямым ребром к нему и её собственные
// атрибуты («дочь Рада, 2010 года рождения»). Два — атрибут ЧУЖОЙ сущности
// («машина Миши»), и это в таблицу не пишется никогда.
//
// 🔒 ПОЧЕМУ ГРАНИЦА ИМЕННО ЗДЕСЬ, А НЕ «ПОГЛУБЖЕ»: без неё «Миша партнёр, у
// которого машина, в которой чехлы, сшитые Машей, которая работает на Мишу»
// попадает в личную память человека целиком. Слово владельца: «это же бред».
// Второй порядок не отбрасывается — он уезжает в граф с якорем (§3п).
//
// 🛑 СТОРОЖ НЕ МОЛЧИТ. Отказ называет причину и адрес: агент, получивший тихое
// «ок» на непринятую запись, считает, что записал.

import type { FactValueType } from "./types"

export type DepthVerdict =
  | { ok: true }
  | { ok: false; reason: DepthRefusal; hint: string }

export type DepthRefusal = "second-order-subject" | "nested-object" | "not-an-object" | "too-many-keys"

/**
 * Сколько полей допускается у объекта глубины 1.
 *
 * 🔒 ПОТОЛОК НУЖЕН НЕ ОТ ЖАДНОСТИ, А ПРОТИВ ПОДМЕНЫ: объект на тридцать полей —
 * это способ протащить в личную таблицу отдельную сущность со своей жизнью,
 * формально не нарушив запрет вложенности.
 */
export const MAX_OBJECT_KEYS = 12

/**
 * Разрешено ли записывать это значение.
 *
 * @param value  что записывают: строка или объект глубины 1
 * @param opts.valueType  объявленный вид значения признака
 * @param opts.subjectIsFirstOrder  субъект — `self` или сущность с прямым ребром к нему
 */
export function checkDepth(
  value: unknown,
  opts: { valueType: FactValueType; subjectIsFirstOrder: boolean },
): DepthVerdict {
  // ── 1. Порядок субъекта ───────────────────────────────────────────────────
  //
  // 🔒 СУБЪЕКТ СУБЪЕКТА СУБЪЕКТОМ НЕ ЯВЛЯЕТСЯ. Факт, чей субъект сам получен как
  // атрибут другой сущности, — второй порядок по определению, каким бы простым
  // ни было его значение.
  if (!opts.subjectIsFirstOrder) {
    return {
      ok: false,
      reason: "second-order-subject",
      hint:
        "это факт о чужой сущности — второй порядок. В личную память не пишу; " +
        "такое уезжает в граф знаний с якорем на сущность первого уровня",
    }
  }

  // ── 2. Простое значение проходит всегда ───────────────────────────────────
  if (typeof value !== "object" || value === null) {
    return { ok: true }
  }

  // 🔒 МАССИВ НЕ ЯВЛЯЕТСЯ ОБЪЕКТОМ ГЛУБИНЫ 1: список сущностей — это способ
  // записать их пачкой в обход правила. Каждая сущность пишется своей строкой.
  if (Array.isArray(value)) {
    return {
      ok: false,
      reason: "not-an-object",
      hint: "список сущностей пишется по одной строке на сущность, а не массивом в одном значении",
    }
  }

  const obj = value as Record<string, unknown>
  const keys = Object.keys(obj)

  if (keys.length > MAX_OBJECT_KEYS) {
    return {
      ok: false,
      reason: "too-many-keys",
      hint: `полей ${keys.length}, потолок ${MAX_OBJECT_KEYS}: объект такого размера — это отдельная сущность, а не атрибут`,
    }
  }

  // ── 3. Один уровень вложенности ───────────────────────────────────────────
  //
  // 🔒 ВТОРОЙ УРОВЕНЬ ВЛОЖЕННОСТИ И ЕСТЬ ГЛУБИНА 2. `{name, role, birthYear}` —
  // атрибуты дочери, глубина 1. `{name, car: {model}}` — атрибуты машины
  // дочери, глубина 2: запись о сущности, связанной с человеком через другую.
  for (const [key, inner] of Object.entries(obj)) {
    if (inner !== null && typeof inner === "object") {
      return {
        ok: false,
        reason: "nested-object",
        hint:
          `поле «${key}» содержит вложенный объект — это глубина 2. ` +
          "Атрибуты чужой сущности живут в графе, а не в личной таблице",
      }
    }
  }

  return { ok: true }
}

/**
 * Значение — в строку для колонки `value_text`.
 *
 * 🔒 ОБЪЕКТ ХРАНИТСЯ JSON-СТРОКОЙ В ТОЙ ЖЕ КОЛОНКЕ, А НЕ В НОВЫХ КОЛОНКАХ НА
 * КАЖДОЕ ПОЛЕ. Поля объекта задаёт человек словами; колонка на поле означала бы
 * `ALTER TABLE` на каждую его фразу — и таблицу, форму которой никто не знает.
 * 🔒 ЧТЕНИЕ РАЗБИРАЕТ ОБРАТНО ПО ВИДУ ЗНАЧЕНИЯ, а не по догадке «похоже на JSON»:
 * человек имеет право написать текстом строку, начинающуюся с фигурной скобки.
 */
export function valueToCell(value: unknown): string {
  if (typeof value === "string") return value.trim()
  if (value === null || value === undefined) return ""
  if (typeof value === "object") return JSON.stringify(value)
  return String(value)
}

/**
 * Строка колонки — обратно в значение.
 *
 * Разбирает JSON только для признаков вида `object`; для остальных возвращает
 * текст как есть.
 */
export function cellToValue(cell: string, valueType: FactValueType | "object"): unknown {
  if (valueType !== "object") return cell
  try {
    const parsed = JSON.parse(cell) as unknown
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : cell
  } catch {
    // 🔒 НЕРАЗБОРНАЯ СТРОКА ОТДАЁТСЯ ТЕКСТОМ, А НЕ РОНЯЕТ ЧТЕНИЕ. Значение могло
    // быть записано до того, как признак объявили объектным.
    return cell
  }
}
