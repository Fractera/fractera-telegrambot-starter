import "server-only";

import { chmodSync, readFileSync, writeFileSync } from "node:fs";

// ОБЩИЙ СКЛАД СЕКРЕТОВ МАШИНЫ — `/etc/fractera/secrets.env`.
//
// 🎯 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-06. Он спросил: «FRACTERA_SLOT_ENV from 3002?» —
// то есть нельзя ли брать эти ключи у панели. Измерение ответило «нет»: у панели
// в `.env.local` лежит ОДИН `DATA_SECRET` из шести нужных, и переключение туда
// поменяло бы одну зависимость на другую, потеряв пять ключей. Бот замолчал бы, а
// выглядело бы это как «ключ не задан».
//
// 🔒 НАСТОЯЩИЙ ХОЗЯИН УЖЕ СУЩЕСТВОВАЛ, И ЭТО НЕ ПРИЛОЖЕНИЕ. `/etc/fractera/secrets.env`
// пишет рождение сервера, права `0600`, владелец root; оттуда читает панель.
// Доказательство, что это секрет МАШИНЫ, а не проекта: `DATA_SECRET` у слота 3000
// и у панели 3002 совпадает — один и тот же `sha256 a1fddeba…`. Файлу гостевого
// приложения такому значению принадлежать нечего.
//
// 🪦 ЗАМЕНЯЕТ `lib/fractera/slot-env.ts` (97-2), КОТОРЫЙ ЧИТАЛ `.env.local` СЛОТА.
// Тот файл был верен, пока служба считалась спутником сайта. С решением
// «служба самодостаточна, порт 3000 ей не родитель» чтение чужого `.env.local`
// стало последней ниткой к соседу. Восстанавливается из git.
//
// 🔒 ПОРЯДОК ИСТОЧНИКОВ НЕ МЕНЯЛСЯ: своё окружение процесса сильнее склада. На
// машине разработчика склада нет вовсе, и служба обязана работать от `.env.local`
// своей папки — этот путь остался прежним у всех потребителей.

const DEFAULT_PATH = "/etc/fractera/secrets.env";

function storePath(): string {
  return process.env.FRACTERA_MACHINE_ENV || DEFAULT_PATH;
}

/**
 * Значение ключа из склада машины. Пусто — ключа нет или файл недоступен.
 *
 * 🔒 ОТСУТСТВИЕ ФАЙЛА — ЗАКОННОЕ СОСТОЯНИЕ, А НЕ ПОЛОМКА: на ноутбуке
 * разработчика `/etc/fractera` не существует, и служба обязана подняться.
 */
export function machineEnv(key: string): string {
  try {
    const raw = readFileSync(storePath(), "utf8");
    return (raw.match(new RegExp(`^${key}=(.+)$`, "m")) ?? [])[1]?.trim() ?? "";
  } catch {
    return "";
  }
}

/**
 * Записать одно значение, не тронув соседние.
 *
 * 🔒 ПОСТРОЧНАЯ ПРАВКА, А НЕ ПЕРЕЗАПИСЬ ФАЙЛА ЦЕЛИКОМ. В складе лежат
 * `AUTH_SECRET`, `DEPLOY_SECRET`, `CHAT_DB_PASSWORD` — значения, потеря которых
 * означает мёртвый сервер. Снимок целиком затирал бы их при каждой правке одного
 * ключа; та же причина, по которой `.env.local` слота правится построчно.
 *
 * 🔒 ПРАВА ВОССТАНАВЛИВАЮТСЯ ПОСЛЕ ЗАПИСИ. Файл обязан остаться `0600`: он лежит
 * вне приложений именно потому, что его не должен читать никто лишний.
 */
export function writeMachineEnv(key: string, value: string): boolean {
  const path = storePath();
  try {
    let raw = "";
    try {
      raw = readFileSync(path, "utf8");
    } catch {
      // Файла нет — законное состояние: создадим.
    }
    const line = `${key}=${value}`;
    const re = new RegExp(`^${key}=.*$`, "m");
    const sep = raw === "" || raw.endsWith("\n") ? "" : "\n";
    const next = re.test(raw) ? raw.replace(re, line) : `${raw}${sep}${line}\n`;
    writeFileSync(path, next, "utf8");
    chmodSync(path, 0o600);
    return true;
  } catch {
    return false;
  }
}
