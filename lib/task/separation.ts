/**
 * Пять родов, и пятый — самый важный.
 *
 *   general          — общий вопрос, не про автоматизацию: «почему корабли не тонут».
 *   automation-read  — вопрос к памяти проекта: ИЗВЛЕЧЬ данные.
 *   automation-write — запрос архитектора: ЗАПИСАТЬ данные.
 *   dev-request      — просьба построить или починить: уезжает заявкой.
 *   unparsed         — разобрать не удалось.
 *
 * 🔒 `unparsed` СУЩЕСТВУЕТ ОТДЕЛЬНЫМ ЗНАЧЕНИЕМ, А НЕ ПУСТОТОЙ. Пустота читается
 * как «сепарация не запускалась»; незнание, не названное незнанием, молча
 * становится категорией — и разбор, который не сработал, выглядит как разбор,
 * решивший «это общий вопрос».
 */
export const MESSAGE_KINDS = [
  "general",
  "automation-read",
  "automation-write",
  "dev-request",
  "unparsed",
] as const
export type MessageKind = (typeof MESSAGE_KINDS)[number]

export function isMessageKind(v: unknown): v is MessageKind {
  return typeof v === "string" && (MESSAGE_KINDS as readonly string[]).includes(v)
}

/**
 * Заводит ли род автоматизацию.
 *
 * 🔒 ОБЩИЙ ВОПРОС НОМЕРА НЕ ПОЛУЧАЕТ. Иначе счётчик наполнится разговорами, и
 * «автоматизация № 400» перестанет что-либо значить для человека, который завёл
 * их три.
 * 🔒 ЗАЯВКА НА РАЗРАБОТКУ — ТОЖЕ НЕ АВТОМАТИЗАЦИЯ: у неё свой адрес, приёмная,
 * и своя судьба. Смешав, мы получили бы номер, за которым не стоит работы.
 */
export function opensAutomation(kind: MessageKind): boolean {
  return kind === "automation-read" || kind === "automation-write"
}

/** Слова о каждом роде — то, что агент скажет человеку строкой о категории. */
const WORDS: Record<MessageKind, { ru: string; en: string }> = {
  general: {
    ru: "общий вопрос — отвечаю без автоматизации",
    en: "a general question — answering without an automation",
  },
  "automation-read": {
    ru: "вопрос к памяти проекта — извлекаю данные",
    en: "a question to the project memory — retrieving data",
  },
  "automation-write": {
    ru: "запрос на запись — сохраняю данные",
    en: "a write request — storing data",
  },
  "dev-request": {
    ru: "просьба о разработке — уходит заявкой, в чате не строим",
    en: "a development request — it becomes a ticket, we do not build it in chat",
  },
  unparsed: {
    ru: "разобрать не удалось — скажу об этом прямо, а не угадаю",
    en: "could not be parsed — I say so plainly instead of guessing",
  },
}

/**
 * Строка о категории — ровно то, что просил владелец на этом этапе.
 *
 * 🔒 ОНА НЕ ОТВЕЧАЕТ ПО СУЩЕСТВУ, И В ЭТОМ ЕЁ СМЫСЛ. Пока разделение не
 * доказано, ответ поверх него доказывает только то, что модель умеет говорить.
 */
export function categoryLine(kind: MessageKind, lang = "ru"): string {
  const w = WORDS[kind]
  const body = lang === "en" ? w.en : w.ru
  return lang === "en" ? `This request is: ${body}.` : `Этот запрос относится к категории: ${body}.`
}
