// СЛОВА ОПОЗДАНИЯ — ЧИСТАЯ ФУНКЦИЯ, И ЛЕЖИТ ОНА ОТДЕЛЬНО ОТ ДВЕРИ (148-2).
//
// 🔒 ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Пока она лежала рядом с тикером, её нельзя было
// проверить прибором: тикер тянет за собой дверь к данным, а та — `server-only`.
// Правило, оплаченное здесь: **чистое отделяется от того, что ходит наружу** —
// иначе проверяемость теряется молча, и её отсутствие обнаруживают в тот день,
// когда правило работает неверно.

export type LateNoteInput = { dueAt: string; tz: string | null }

/**
 * Пометка «должно было прийти в …».
 *
 * 🔒 НАЗЫВАЕТ ИСХОДНОЕ ВРЕМЯ, А НЕ ИЗВИНЯЕТСЯ. Это факт, по которому человек
 * поймёт, что он ничего не забыл, — опоздали мы.
 * 🔒 ВРЕМЯ МЕСТНОЕ, А НЕ СЕРВЕРНОЕ. Сервер живёт в UTC; напечатав его час,
 * пометка сообщила бы человеку время, которого он не называл.
 * 🔒 БЕЗ ЗОНЫ ПЕЧАТАЕТСЯ СЫРОЙ СРОК, А НЕ ВЫДУМАННОЕ МЕСТНОЕ: подстановка
 * какой-нибудь зоны была бы правдоподобной ложью о том, когда это должно было
 * случиться.
 */
export function lateNote(entry: LateNoteInput): string {
  if (!entry.tz) return `Должно было прийти в ${entry.dueAt}.`
  const local = new Date(entry.dueAt).toLocaleString("ru-RU", {
    timeZone: entry.tz,
    hour: "2-digit",
    minute: "2-digit",
  })
  return `Должно было прийти в ${local} (${entry.tz}).`
}
