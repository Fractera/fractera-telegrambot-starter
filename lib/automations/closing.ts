import type { ClosingKind } from "./store"

/** Что известно о прогоне к моменту закрытия. Всё — из записей, не из суждений. */
export type RunFacts = {
  automationId: number
  /** Сколько сообщений в цепочке. */
  messages: number
  /** Ключи сработавших признаков реестра. */
  factKeys: string[]
  /** Звались ли инструменты, и какие. */
  tools: string[]
  /** Было ли извлечение из медиа — фото, голоса, видео. */
  fromMedia: boolean
  /** Есть ли следующая ступень цепочки. */
  hasNextStep: boolean
  /** Имя публичного договора, если автоматизация отвечает наружу. */
  publicContract: string | null
  /** Спрашивали ли уже отзыв по этому номеру. */
  feedbackAsked: boolean
  /** Каких признаков не хватило при разборе. */
  missingFacts: string[]
}

export const CLOSING_ACTIONS = [
  "next-step",
  "ask-feedback",
  "refresh-public",
  "dev-request",
  "propose-fact",
] as const
export type ClosingAction = (typeof CLOSING_ACTIONS)[number]

export type Decision = {
  action: ClosingAction
  do: boolean
  /** Почему — словами. Пустой причины не бывает: молчание читается как поломка. */
  why: string
}

/**
 * Порог «представляет интерес» — слова владельца, переведённые в число.
 *
 * 🔒 ПРАВИЛО НАД ФАКТАМИ, А НЕ СУЖДЕНИЕ МОДЕЛИ. Владелец назвал признаки сам:
 * сложный цикл, специальный навык, вызов инструментов, извлечение из медиа.
 */
export function isInteresting(run: RunFacts): boolean {
  return run.tools.length > 0 || run.fromMedia || run.messages >= 4 || run.factKeys.length >= 3
}

/**
 * Что делать при закрытии — список решений с причинами.
 *
 * 🔒 РЕШЕНИЕ «НЕ ДЕЛАТЬ» ТОЖЕ ВОЗВРАЩАЕТСЯ, И В ЭТОМ ВЕСЬ СМЫСЛ. Пустой список
 * читается как «ничего не случилось»; список с причинами показывает, что система
 * подумала и отказалась — «отзыв не запрашивался: цикл короткий».
 *
 * 🔒 ЗАКРЫТИЕ ШАГА И ЗАКРЫТИЕ ЦЕЛИКОМ РАЗЛИЧАЮТСЯ ЗДЕСЬ, А НЕ У ВЫЗЫВАЮЩЕГО.
 * Шаг, закрытый как автоматизация, оборвал бы цепочку; автоматизация, закрытая
 * как шаг, никогда не спросила бы отзыв.
 */
export function decideClosing(run: RunFacts, kind: ClosingKind): Decision[] {
  const step = kind === "step"
  return [
    {
      action: "next-step",
      do: step && run.hasNextStep,
      why: !step
        ? "закрыта целиком — следующей ступени нет по определению"
        : run.hasNextStep
          ? "закрыт шаг цепочки, следующая ступень объявлена"
          : "закрыт шаг, но следующей ступени не объявлено",
    },
    {
      action: "ask-feedback",
      do: !step && isInteresting(run) && !run.feedbackAsked,
      why: step
        ? "закрыт шаг, а не работа целиком — спрашивать рано"
        : run.feedbackAsked
          ? "отзыв по этому номеру уже запрашивали"
          : isInteresting(run)
            ? "цикл содержательный: звались инструменты либо разбор был длинным"
            : "цикл короткий и без инструментов — предложение было бы назойливостью",
    },
    {
      action: "refresh-public",
      do: !step && Boolean(run.publicContract),
      why: step
        ? "закрыт шаг — публичная страница обновляется по завершении работы целиком"
        : run.publicContract
          ? `у автоматизации есть публичный договор «${run.publicContract}»`
          : "наружу не отвечает — обновлять нечего",
    },
    {
      action: "dev-request",
      do: !step && run.missingFacts.length > 0 && run.tools.length === 0,
      why: step
        ? "закрыт шаг — о недостающем судят по работе целиком"
        : run.missingFacts.length === 0
          ? "всё нужное система уже умеет"
          : run.tools.length > 0
            ? "инструменты сработали — задача решена имеющимся"
            : "нужного не хватило, и инструмента для этого нет",
    },
    {
      action: "propose-fact",
      do: !step && run.missingFacts.length > 0,
      why: step
        ? "закрыт шаг — предложение признака ждёт завершения работы целиком"
        : run.missingFacts.length > 0
          ? `при разборе не хватило признаков: ${run.missingFacts.join(", ")}`
          : "все нужные признаки в реестре есть",
    },
  ]
}

