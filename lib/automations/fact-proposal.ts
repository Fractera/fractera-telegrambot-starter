import { readAutomationRows } from "./rows"
import { allFacts } from "@/lib/facts/registry"
import { scopeValue } from "@/lib/facts/scope"

// ПРЕДЛОЖЕНИЕ ПРИЗНАКА — ПЯТОЕ ДЕЙСТВИЕ ЗАКРЫТИЯ (143-7).
//
// 🔒 ПРЕДЛАГАЕТ, НО НЕ ПРИМЕНЯЕТ — ЗАКОН `fact-draft`, ВЗЯТЫЙ ДОСЛОВНО. Признак,
// заведённый системой самой, меняет то, что она понимает: завтра она разберёт
// сообщение иначе, и никто не сможет сказать, почему. Это решение владельца, а
// не побочный эффект удачного разговора.
//
// 🔒 ИСТОЧНИК ЧЕСТНЕЕ ЗАМЫСЛА ЗАГЛУШКИ. `registry-evolution` задумывался
// машинным: копить облако смыслов и при пороге предлагать признак. Здесь
// источник — КОНКРЕТНЫЙ ПРОГОН, которому КОНКРЕТНОГО признака не хватило.
// Порог не нужен: нехватка уже случилась, и её видно строкой.
//
// 🔒 ЧТО ТАКОЕ «НЕ ХВАТИЛО» МЕХАНИЧЕСКИ: строка `reveal` с ПУСТЫМ ключом. Это
// законный исход `no-fact` — «признака под это в реестре НЕТ», — а не потеря.
// Закон владельца, сформулированный отрицанием: нет признака в реестре — нет
// инструкции, как это декомпозировать, значит факт останется просто текстом.

export type FactProposal = {
  /** Фраза человека, под которую признака не нашлось. Дословно. */
  said: string
  /** Ключ-кандидат — ПРЕДЛОЖЕНИЕ, а не имя. Заводит его человек. */
  candidateKey: string
  /** На что похоже из уже заведённого: сходство считается общим началом ключа. */
  near: string[]
  /** Сколько раз это встретилось в прогоне. */
  times: number
}

/**
 * Собрать предложения по ленте прогона.
 *
 * 🔒 РЕЕСТР ПРИ ЭТОМ НЕ МЕНЯЕТСЯ — И ЭТО ПРОВЕРЯЕМОЕ УТВЕРЖДЕНИЕ, А НЕ ОБЕЩАНИЕ:
 * writeFact отсюда не зовётся, и прибор сверяет число записей до и после.
 */
export async function proposeFacts(automationId: number): Promise<FactProposal[]> {
  const rows = await readAutomationRows(automationId)
  const missing = rows.filter(r => r.kind === "reveal" && !(r.fact ?? "").trim())
  if (missing.length === 0) return []

  const known = allFacts().map(f => f.key)
  const byPhrase = new Map<string, number>()
  for (const row of missing) {
    const said = (row.phrase ?? "").trim()
    if (!said) continue
    byPhrase.set(said, (byPhrase.get(said) ?? 0) + 1)
  }

  return [...byPhrase.entries()].map(([said, times]) => {
    const candidateKey = candidate(said)
    return { said, candidateKey, near: nearest(candidateKey, known), times }
  })
}

/**
 * Ключ-кандидат из фразы.
 *
 * 🔒 ЭТО ЧЕРНОВИК, А НЕ ИМЯ. Настоящий ключ придумывает человек: имя вечное, на
 * нём повиснут таблица и запросы. Кандидат нужен ровно для того, чтобы владельцу
 * было что править, а не сочинять с нуля.
 * 🔒 КИРИЛЛИЦА НЕ УГАДЫВАЕТСЯ И НЕ ПРОПУСКАЕТСЯ: белый список её не примет, и без
 * перевода ни одна русская фраза не получила бы кандидата вовсе. Здесь перевода
 * нет намеренно — вместо выдуманного ключа возвращается пустой, и это честнее:
 * таблица перевода живёт в `lib/facts/scope.ts` и принадлежит охвату, а второй
 * её копии тут не заводится.
 */
function candidate(said: string): string {
  // 🔒 КИРИЛЛИЦА ПЕРЕВОДИТСЯ ТОЙ ЖЕ ТАБЛИЦЕЙ, ЧТО У ОХВАТА, А НЕ ВТОРОЙ СВОЕЙ.
  // ✗ НАЙДЕНО ПРИБОРОМ 2026-09-08: без перевода «погода за окном» давала ПУСТОЙ
  // кандидат — то есть кандидат был пуст ВСЕГДА, потому что человек говорит
  // по-русски. Ошибка выглядела как предусмотрительность: в комментарии стояло
  // «вместо выдуманного ключа возвращается пустой», и это было правдой ровно в
  // той мере, в какой бесполезно.
  // 🔒 ВТОРОЙ ТАБЛИЦЫ НЕ ЗАВОДИТСЯ: две транслитерации разошлись бы, и один
  // предмет получил бы два ключа — ровно тот дефект, что найден в 83 на именах.
  // ✗ ЗДЕСЬ УЖЕ БЫЛ ПОТЕРЯН ОБРАТНЫЙ СЛЭШ — ВТОРОЙ РАЗ ЗА ДВЕ СЕССИИ, И ПРИЧИНА
  // ТА ЖЕ, ЧТО В `proxy.ts:44`: строка писалась через скрипт, и оболочка съела
  // экранирование. Образец `[s,.;:!?]` компилируется и работает — просто делает
  // НЕ ТО: «погода за окном» давала ключ `misc.pogoda-za-oknom` вместо `pogoda.za`.
  // 🔒 ЭТОТ КЛАСС НЕ ЛОВИТСЯ НИ ТИПАМИ, НИ СБОРКОЙ — только замером на живой фразе.
  const words = said.trim().toLowerCase().split(/[\s,.;:!?]+/).filter(Boolean).slice(0, 3)
  const parts = words.map(w => scopeValue(w)).filter(Boolean)
  if (parts.length === 0) return ""
  // 🔒 ЭТО ЧЕРНОВИК, А НЕ ИМЯ. Настоящий ключ придумывает человек: имя вечное, на
  // нём повиснут таблица и запросы. Кандидат нужен, чтобы было что править.
  return parts.length >= 2 ? `${parts[0]}.${parts[1]}` : `misc.${parts[0]}`
}


/**
 * Что уже есть похожего.
 *
 * 🔒 СХОДСТВО СЧИТАЕТСЯ ОБЩИМ НАЧАЛОМ КЛЮЧА, И ПРИЁМ ГРУБЫЙ НАМЕРЕННО — тот же,
 * что у двойников человека (83). Правило «это то же самое» пишется легко и
 * ошибается необратимо: слитых обратно не разделить. Решает владелец.
 */
function nearest(key: string, known: string[]): string[] {
  const head = key.split(".")[0]
  if (!head) return []
  return known.filter(k => k.split(".")[0] === head).slice(0, 5)
}
