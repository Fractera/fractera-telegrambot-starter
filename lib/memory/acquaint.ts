import { allFacts } from "@/lib/facts/registry"

// ЗНАКОМСТВО КАК КОНСТРУКЦИЯ, А НЕ КАК ПАМЯТЬ МОДЕЛИ (163-2).
//
// 🎯 ВОПРОС ВЛАДЕЛЬЦА 2026-09-08: «моё первое общение запускает инструкцию
// первого знакомства — или такого нет?» Ответ был честным: навык есть, запуска
// нет, и знакомство случалось ровно настолько, насколько модель вспоминала о нём
// в этот ход. Правило, живущее в словах, исполняется настолько же (§10.5).
//
// 🔒 ПАМЯТЬ САМА ГОВОРИТ, ЧЕГО О ЧЕЛОВЕКЕ НЕ ЗНАЕТ, И ЧТО СПРОСИТЬ ПЕРВЫМ.
// Она единственная, кто это видит: у неё на руках и реестр признаков, и то, что
// уже записано. Агенту остаётся произнести вопрос — и не открывать ради этого
// целый навык (закон 158-4: дорого стоит ход модели, а не запрос к базе).
//
// 🛑 СПРАШИВАЕТСЯ ОДИН ПРИЗНАК, А НЕ СПИСОК. Тринадцать вопросов подряд человек
// не проходит — он уходит; это записано в навыке `first-acquaintance` и оплачено
// не нами. Поэтому здесь всегда ровно один следующий вопрос.

export type Acquaint = {
  /** Ключ признака, который стоит узнать следующим. */
  key: string
  /** Готовая фраза человеку на его языке — произносится как есть. */
  ask: string
  /** Зачем это системе: причина, которую не стыдно назвать вслух. */
  why: string
  /** Сколько признаков знакомства ещё не заполнено, включая этот. */
  left: number
}

/**
 * Слова вопроса — по-русски и по-английски.
 *
 * 🔒 ДВА ЯЗЫКА, А НЕ 82, И ЭТО ТОТ ЖЕ ЗАКОН, ЧТО У СЛОЯ АРХИТЕКТОРА: сюда приходит
 * хозяин проекта, и он уже пришёл.
 * 🔒 ПРИЧИНА НАЗЫВАЕТСЯ ВМЕСТЕ С ВОПРОСОМ. Вопрос без причины читается как
 * любопытство, получает отказ — и второй раз его уже не задать (закон 141).
 */
const WORDS: Record<string, { ru: [string, string]; en: [string, string] }> = {
  "person.address-form": {
    en: ["Should I keep it formal or informal with you?", "every reply is built on this"],
    ru: ["На «ты» или на «вы»?", "на этом строится каждый ответ"],
  },
  "person.city": {
    en: ["Where are you based?", "advice depends on the place"],
    ru: ["Где вы находитесь?", "от места зависят советы и сроки"],
  },
  "person.language": {
    en: ["Which language should I answer in?", "so I do not switch languages by accident"],
    ru: ["На каком языке отвечать?", "чтобы не переключаться случайно"],
  },
  "person.name": {
    en: ["What should I call you?", "so I do not address you as a stranger"],
    ru: ["Как к вам обращаться?", "чтобы не обращаться к вам никак"],
  },
  "person.timezone": {
    en: ["Which time zone are you in?", "without it a reminder cannot be set at all"],
    ru: ["В каком вы часовом поясе?", "без него срок напоминания не создаётся вовсе"],
  },
}

/**
 * Что спросить следующим — и надо ли спрашивать вообще.
 *
 * 🔒 ПОРЯДОК БЕРЁТСЯ ИЗ РЕЕСТРА (`askOrder`), А НЕ ИЗ СПИСКА В КОДЕ. Он про смысл
 * признака: без часового пояса не создаётся срок, без обращения каждый ответ
 * звучит не так. Список в коде разошёлся бы с реестром на первой правке — тот же
 * закон, что у чисел в инструкциях.
 * 🛑 ПРИЗНАК БЕЗ `askOrder` В ЗНАКОМСТВЕ НЕ УЧАСТВУЕТ, и это законное состояние:
 * национальность или валюта узнаются по ходу дела, а не при встрече.
 */
export function nextQuestion(known: Set<string>, lang: string | null | undefined): Acquaint | null {
  const code = String(lang ?? "").trim().slice(0, 2).toLowerCase() === "en" ? "en" : "ru"
  const queue = allFacts()
    .filter(f => typeof f.askOrder === "number" && !known.has(f.key))
    .sort((a, b) => (a.askOrder ?? 0) - (b.askOrder ?? 0))
  const first = queue[0]
  if (!first) return null
  const words = WORDS[first.key]
  // 🛑 ПРИЗНАК ЕСТЬ, А СЛОВ НЕТ — ЭТО НАШ ДОЛГ, А НЕ ПОВОД ВЫДУМАТЬ ФРАЗУ.
  // Придуманный на ходу вопрос звучит как анкета и портит первое впечатление;
  // молчание честнее. Долг виден: признак с `askOrder` без слов пропускается.
  if (!words) return null
  const [ask, why] = words[code]
  return { ask, key: first.key, left: queue.length, why }
}

/**
 * Готовая фраза для ОДНОГО названного признака — для блокирующего вопроса (165-5).
 *
 * 🔒 ЭТО ТОТ ЖЕ СЛОВАРЬ, ЧТО У ЗНАКОМСТВА, И ВТОРОГО ЗАВОДИТЬ НЕЛЬЗЯ. Вопрос
 * человеку звучит одинаково независимо от того, почему его задают: разные слова
 * для одного и того же признака — это две редакции одной фразы, и через месяц
 * они разойдутся. Разное здесь — не текст, а СРОЧНОСТЬ.
 * 🛑 НЕТ СЛОВ — НЕТ ВОПРОСА. Придуманная на ходу фраза звучит как анкета; это то
 * же правило, что у `nextQuestion`, и по той же причине.
 */
export function askFor(key: string, lang: string | null | undefined): { ask: string; why: string } | null {
  const code = String(lang ?? "").trim().slice(0, 2).toLowerCase() === "en" ? "en" : "ru"
  const words = WORDS[key]
  if (!words) return null
  const [ask, why] = words[code]
  return { ask, why }
}
