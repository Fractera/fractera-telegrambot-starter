function capLimit(v: unknown): number {
  const n = typeof v === "number" && Number.isFinite(v) ? Math.floor(v) : 20
  return Math.min(Math.max(n, 1), 50)
}

/**
 * Что известно.
 *
 * 🔒 СНАРУЖИ ЭТО ОДИН ВОПРОС. Внутри — ступени: значения признаков о человеке;
 * механический поиск по его словам, когда ключ неизвестен; и, если разрешено
 * бюджетом, знание об окружении. Зовущий не знает, что источников несколько, и
 * не тратит ходы модели на выбор между ними (закон 158-4).
 */
export async function read(input: {
  query?: string
  key?: string
  subject?: string
  budget?: string
  depth?: number
  approved?: boolean
  limit?: number
}): Promise<MemoryReadResult> {
  const subject = String(input.subject ?? "").trim() || "self"
  const query = String(input.query ?? "").trim()
  const key = String(input.key ?? "").trim().toLowerCase()
  const limit = capLimit(input.limit)
  const searched: string[] = [query, key].filter(Boolean)

  // ── ГЛУБИНА ЧИСЛОМ, УМОЛЧАНИЕ — ПЕРВЫЙ УРОВЕНЬ (162-3) ──────────────────
  //
  // 🪦 `budget: "deep"` ОСТАВЛЕН РАБОЧИМ ПСЕВДОНИМОМ ГЛУБИНЫ 2, а не удалён:
  // его знают инструкция агента, приборы 161-3 и живая сессия канала. Имя,
  // исчезнувшее молча, ломает зовущих без единого сообщения об ошибке.
  const askedDepth = Number(input.depth)
  const depth = Number.isFinite(askedDepth) && askedDepth >= 1
    ? Math.min(Math.floor(askedDepth), MAX_DEPTH)
    : String(input.budget ?? "").trim() === "deep"
      ? 2
      : 1
  const approved = input.approved === true
  const levels: LevelReport[] = []
  // 🔒 МЕТКИ, ПОДТВЕРЖДЁННЫЕ ГРАФОМ НА УРОВНЕ 2, — ОСНОВА ОБЛАКА ДЛЯ УРОВНЯ 3.
  // Живут здесь, а не внутри уровня: это и есть передача находки дальше по цепочке.
  const askedLabels: string[] = []

  // 🔒 ГЛУБЖЕ ИМЕЕТ СМЫСЛ ТОЛЬКО ПРИ СВОБОДНОМ ВОПРОСЕ. Знание об окружении
  // отвечает словами человека, а не ключами признаков: предлагать углубление
  // там, где спросили конкретный ключ, значит обещать то, чего оно не умеет.
  const canDeepen = query.length > 0
  // 🔒 ПРЕДЛОЖЕНИЕ НАЗЫВАЕТ ЦЕНУ СЛЕДУЮЩЕГО УРОВНЯ, А НЕ ОБЩУЮ (162-4). Одна
  // цифра на все углубления была бы неправдой в обе стороны: связи дешевле, чем
  // обещано, вектор с облаком дороже.
  const next = LEVELS[Math.min(depth, MAX_DEPTH - 1)]
  const offer: Deeper = {
    available: canDeepen && depth < MAX_DEPTH,
    cost_seconds: Math.max(1, Math.round(next.ms / 1000)),
    what: canDeepen
      ? next.needsApproval
        ? `поискать глубже: ${next.what}. Дорогой уровень — сначала спроси человека и позови с approved: true`
        : `поискать глубже: ${next.what}`
      : "глубже искать нечем: для этого нужен вопрос словами, а не ключ",
  }
  const noDeeper: Deeper = { available: false, cost_seconds: 0, what: "глубже идти уже некуда" }

  // ── КАРТА ПОИСКА: С ЧЕМ ВООБЩЕ МОЖЕТ БЫТЬ СВЯЗАН ЭТОТ ВОПРОС (162-1) ──────
  //
  // 🔒 СЧИТАЕТСЯ ДО ЧТЕНИЯ И ВОЗВРАЩАЕТСЯ ВСЕГДА — И ПРИ НАХОДКЕ, И ПРИ ПРОМАХЕ.
  // Промах без карты неотличим от «искали не там»; с картой видно, что система
  // сочла относящимся к вопросу и где собиралась смотреть.
  // 🛑 БЕЗ ВЫЗОВА МОДЕЛИ: это механическое сопоставление основ слов (закон 157-5).
  const hits = query ? candidates(query, { limit: 12 }).hits : []
  const looked: LookedAt[] = hits.map(c => ({
    key: c.key,
    title: c.title,
    where: c.placement.kind === "none" ? c.placement.why : c.placement.table,
    why: c.why,
  }))

  const items: MemoryItem[] = []
  const missing: Missing[] = []
  // 🔒 КЛЮЧИ ПРИЗНАКОВ ЧЕЛОВЕКА, ЕСЛИ ОНИ УЖЕ ПРОЧИТАНЫ ПО ХОДУ (163-2): очередь
  // знакомства считается по ним, и второго похода в базу за тем же не делается.
  let selfKeys: Set<string> | null = null
  const startedLevel1 = Date.now()

  // ── СТУПЕНЬ 0: ТО, ЧТО ЗАПИСАНО ───────────────────────────────────────────
  if (key) {
    const fact = allFacts().find(f => f.key === key)
    const placed = fact ? placementOf(fact) : null
    // 🔒 У ЧУЖОЙ КОЛОНКИ СУЖЕНИЕ ПО СУБЪЕКТУ НЕ ПРОСТО НЕ РАБОТАЕТ — `recall`
    // ОТКАЗЫВАЕТ, увидев его (там нет колонки субъекта). Спрашивать надо так,
    // как хранилище умеет отвечать, и честно называть, что ответ по всем записям.
    const byColumn = placed?.kind === "column"
    const got = await recall(key, byColumn ? { limit } : { subject, limit })
    if (got.found === true) {
      for (const v of got.items) {
        items.push({
          about: byColumn ? "all-records" : "self",
          at: v.at,
          basis: v.basis,
          claim: v.claim,
          from: placed ? placeAddress(placed) : "",
          key,
          scope: v.scope,
          title: fact?.title ?? key,
          value: v.value,
        })
      }
    } else if (fact && placed) {
      missing.push({
        key,
        title: fact.title,
        where: placeAddress(placed),
        why: got.hint ?? "значений нет",
      })
    }
  } else if (query) {
    // ── УРОВЕНЬ 1: ЧИТАЕМ ВСЕ ТАБЛИЦЫ-КАНДИДАТЫ, А НЕ ТОЛЬКО ЛИЧНЫЕ (162-2) ──
    //
    // 🎯 ТРЕБОВАНИЕ ВЛАДЕЛЬЦА: «делаешь извлечение данных из соответствующих
    // таблиц» — из соответствующих, а не из тех, что про самого человека.
    //
    // ✗ ЧЕМ ОПЛАЧЕНО. Прежний код брал кандидатов и тут же выбрасывал каждого,
    // у кого `subject !== "self"`, а остальных спрашивал С СУЖЕНИЕМ по субъекту —
    // на что `recall` у чужой колонки отвечает отказом по устройству. Два
    // независимых запрета на один путь: значения из `tgdesk_messages` (17
    // признаков), `tgdesk_entries` (6) и `tgdesk_artifacts` (3) не находились
    // вопросом человека НИКОГДА. Измерено 2026-09-08: 14 записей из 49.
    //
    // 🔒 ПРЕДЕЛ УРОВНЯ 1 — ЧИСЛО ЗАПРОСОВ, А НЕ ЧИСЛО ЗНАЧЕНИЙ, и он существует
    // ради цели владельца: «возвращать необходимое количество информации запросом
    // первого уровня, чтобы обеспечить реактивную работу». Каждый кандидат — это
    // поход в слой данных; непрочитанные названы в `missing`, а не забыты.
    const LEVEL1_READS = 8
    const toRead: { key: string; title: string; address: string; byColumn: boolean; strong: boolean }[] = []
    for (const hit of hits) {
      const fact = allFacts().find(f => f.key === hit.key)
      if (!fact) continue
      const placed = placementOf(fact)
      const address = placeAddress(placed)
      if (placed.kind === "none") {
        // Ветвь разбора: значений нет по устройству — это не промах и не отказ.
        missing.push({ key: hit.key, title: fact.title, where: address, why: placed.why })
        continue
      }
      if (toRead.length >= Math.min(LEVEL1_READS, limit)) {
        missing.push({
          key: hit.key,
          title: fact.title,
          where: address,
          why: "не читали: достигнут предел первого уровня — спросите точнее или углубитесь",
        })
        continue
      }
      // 🔒 `strong` ЕДЕТ ДО САМОГО ЗНАЧЕНИЯ (165-3): по нему потом видно, отвечали
      // мы на заданный вопрос или принесли похожее. Слабое совпадение — это два
      // слова из ОПИСАНИЯ записи, а не из слов человека.
      toRead.push({
        address,
        byColumn: placed.kind === "column",
        key: hit.key,
        strong: hit.strong === true,
        title: fact.title,
      })
    }

    // 🔒 ЧТЕНИЯ УРОВНЯ 1 ИДУТ ОДНОВРЕМЕННО, А НЕ ПО ОЧЕРЕДИ — И ЭТО ПРЯМОЕ
    // ИСПОЛНЕНИЕ ЦЕЛИ ВЛАДЕЛЬЦА О РЕАКТИВНОСТИ, А НЕ УКРАШЕНИЕ.
    // ✗ ИЗМЕРЕНО ПРИБОРОМ 161-3 В ТОТ ЖЕ ЧАС: последовательный обход восьми
    // кандидатов стоил **1251 мс** — каждый признак это свой поход в слой данных,
    // и они складывались. Уровень, объявленный «мгновенным», был секундой.
    // 🔒 ПОРЯДОК ОТВЕТА ПРИ ЭТОМ СОХРАНЁН: одновременность меняет время, а не
    // очерёдность — значения ложатся в том же порядке, в каком совпали с вопросом.
    // 🛑 СУЖЕНИЕ ПО СУБЪЕКТУ — ТОЛЬКО ТАМ, ГДЕ ЕСТЬ ЧЕМ СУЖАТЬ: у чужой колонки
    // такой колонки нет, и `recall` на сужение отвечает отказом по устройству.
    // 🔒 СКОЛЬКО ЗНАЧЕНИЙ БРАТЬ — ГОВОРИТ РЕЕСТР, А НЕ КОД (165-3). У признака с
    // накоплением `list` значений много и ВСЕ они верны: знакомые, проекты,
    // запреты. У `last` верно последнее.
    // ✗ ОПЛАЧЕНО ДВУМЯ ПРОГОНАМИ: чтение брало ОДНУ строку у всех подряд, и
    // список из восьми знакомых приезжал одним человеком — а дальше это ОДНО имя
    // становилось якорем связей. Кейс «кто из моих друзей мог знать президента»
    // отвечал про того, чья строка оказалась первой, и на корпусе из одного друга
    // это было неотличимо от правильной работы.
    const LIST_READS = 6
    const many = (k: string) => (allFacts().find(f => f.key === k)?.aggregate === "list" ? LIST_READS : 1)
    const got = await Promise.all(
      toRead.map(t => recall(t.key, t.byColumn ? { limit: many(t.key) } : { limit: many(t.key), subject }))
    )
    for (let i = 0; i < toRead.length; i += 1) {
      const t = toRead[i]
      const r = got[i]
      if (r.found === true && r.items.length > 0) {
        // 🔒 ВСЕ ЗНАЧЕНИЯ СПИСКА ЕДУТ В ОТВЕТ, В ТОМ ЖЕ ПОРЯДКЕ, ЧТО ОТДАЛО
        // ХРАНИЛИЩЕ: из них строятся якоря уровня 2, и потеря здесь ниже уже не
        // восстановима. У признака с `last` элемент ровно один — цикл вырождается.
        for (const v of r.items) {
          items.push({
            // 🛑 ЗНАЧЕНИЕ ИЗ ЧУЖОЙ ТАБЛИЦЫ НЕ ОБЪЯВЛЯЕТСЯ ФАКТОМ О ЧЕЛОВЕКЕ.
            about: t.byColumn ? "all-records" : "self",
            at: v.at,
            basis: v.basis,
            claim: v.claim,
            from: t.address,
            key: t.key,
            scope: v.scope,
            title: t.title,
            value: v.value,
            weak: t.strong ? undefined : true,
          })
        }
      } else {
        missing.push({
          key: t.key,
          title: t.title,
          where: t.address,
          why: r.found === false ? r.hint ?? "значений нет" : "значений нет",
        })
      }
    }
  } else {
    // 🔒 НИ КЛЮЧА, НИ ВОПРОСА — ЭТО «ЧТО ТЫ ЗНАЕШЬ ОБО МНЕ», И ЭТО ОДИН ВОПРОС.
    const all = await recallSubject(subject, { limit })
    if (all.found === true) {
      selfKeys = new Set(all.items.map(v => v.key))
      for (const v of all.items) {
        const fact = allFacts().find(f => f.key === v.key)
        items.push({
          // Это ответ на «что ты знаешь обо мне»: сюда попадают только личные
          // таблицы, у них субъект есть и он спрошен.
          about: "self",
          at: v.at,
          basis: v.basis,
          claim: v.claim,
          from: fact ? placeAddress(placementOf(fact)) : "",
          key: v.key,
          scope: v.scope,
          title: v.title,
          value: v.value,
        })
      }
    }
  }

  levels.push({
    added: items.length,
    level: 1,
    ms: Date.now() - startedLevel1,
    name: LEVELS[0].name,
    note: items.length === 0 ? "в записанном значений нет" : undefined,
  })

  // ── УРОВЕНЬ 2: СВЯЗИ, И СПРАШИВАЮТСЯ ОНИ ИМЕНАМИ ИЗ УРОВНЯ 1 (162-3) ──────
  //
  // 🎯 ЦЕПОЧКА, ОПИСАННАЯ ВЛАДЕЛЬЦЕМ: «берёт из обычной базы список всех друзей…
  // по каждому другу запускает поиск». Найденное на уровне 1 становится ЗАПРОСОМ
  // уровня 2 — это и есть обогащение, ради которого лестница заведена.
  //
  // ✗ ДО ЭТОЙ ПРАВКИ ЗДЕСЬ СТОЯЛ РАННИЙ ВОЗВРАТ: нашлось на уровне 1 — ответ
  // отдавался немедленно, и связи не спрашивались НИКОГДА. Кейс «друг Денис →
  // его история» не работал ни при каких данных именно поэтому.
  if (depth >= 2 && query) {
    const started = Date.now()
    const before = items.length
    const anchors = anchorsFrom(items)
    // 🔒 ЯКОРЬ ДОБАВЛЯЕТСЯ К ВОПРОСУ ЧЕЛОВЕКА, А НЕ ЗАМЕНЯЕТ ЕГО.
    //
    // ✗ ОПЛАЧЕНО В ТОТ ЖЕ ЧАС, И ПОЙМАЛ ЭТО ЧУЖОЙ ПРИБОР (161-3). Первая версия
    // спрашивала связи ТОЛЬКО якорями. Но не всякое личное значение — имя
    // сущности: валюта `EUR`, род занятий, тон обращения тоже лежат в личных
    // таблицах. Вопрос «что известно о человеке по фамилии Ратмиров» уходил в
    // связи словом «EUR» — и находка, которую прежний путь давал уверенно,
    // пропадала. **Обогащение, потерявшее исходный вопрос, — это не обогащение,
    // а подмена.**
    // 🔒 ИЗМЕРЕНО ТОГДА ЖЕ, ОДИН ВОПРОС, ПЯТЬ РЕЖИМОВ: вектор (`naive`) находит
    // нужный документ и с рерайтом, и без — 742–856 мс; связи (`local`) на той же
    // фразе не находят его ВОВСЕ. Значит фраза человека обязана доехать до
    // вектора, а якоря работают там, где сильны связи, — на именах.
    // 🛑 ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: отбора «а знает ли граф такое имя» — он стоит
    // одного чтения меток и строится подшагом 162-8. До него лишний якорь стоит
    // одного запроса, а не потерянного ответа.
    // ── ПРЕДФИЛЬТР ПО МЕТКАМ ГРАФА (162-8) ─────────────────────────────────
    //
    // 🔒 СПРАШИВАЕМ СВЯЗИ ТОЛЬКО О ТОМ, ЧТО ГРАФ ЗНАЕТ. Проверка имени стоит
    // 41 мс, вопрос о нём — 551 мс: у десяти имён это разница между полусекундой
    // и шестью секундами. И имя приходит в написании ГРАФА, а не человека.
    // 🛑 ВОПРОС ЧЕЛОВЕКА ПРЕДФИЛЬТР НЕ ПРОХОДИТ И ПРОХОДИТЬ НЕ ДОЛЖЕН: он идёт
    // вектором, которому метки безразличны (закон 162-3, оплаченный потерей находки).
    // 🔒 ВАРИАНТЫ ОДНОГО ИМЕНИ СЧИТАЮТСЯ ОДНИМ ЯКОРЕМ ПРИ ПОДСЧЁТЕ ПРЕДЕЛА, НО
    // СПРАШИВАЮТСЯ ВСЕ (168-2). Иначе два написания «Памяти» съели бы бюджет,
    // отведённый другим именам, — и починка потери обернулась бы новой потерей.
    // Предел здесь про ЧИСЛО СУЩНОСТЕЙ, а не про число запросов к связям.
    const known: string[] = []
    const unknown: string[] = []
    let namesTaken = 0
    for (const a of anchors) {
      const spellings = await matchLabel(a)
      if (spellings.length === 0) {
        unknown.push(a)
        continue
      }
      if (namesTaken >= MAX_ANCHORS) break
      namesTaken += 1
      known.push(...spellings)
    }
    askedLabels.push(...known)
    // 🛑 ПОТОЛОК ЗАПРОСОВ ОСТАЁТСЯ, И ОН ШИРЕ ЧИСЛА ИМЁН РОВНО НА ИХ НАПИСАНИЯ:
    // каждое стоит одного похода в связи (551 мс), и без потолка десять
    // двойников превратили бы ответ в минуту ожидания.
    const asking = [...new Set([...known, query])].slice(0, MAX_ANCHORS * 2 + 1)
    for (const q of asking) {
      // ── КАКИМ РЕЖИМОМ СПРАШИВАТЬ — ИЗМЕРЕНО (161-3) ────────────────────
      //
      // 🔒 ЗАМЕР: «Ратмиров» (одно слово, по связям) — нашёл · та же фраза
      // целиком строчными — НЕ нашёл · она же вектором — нашёл. Связи вынимают
      // из вопроса ИМЕНА и сверяют регистр; вектор сравнивает смысл фразы.
      // 🛑 ЧЕЛОВЕК В TELEGRAM ПИШЕТ СТРОЧНЫМИ ЦЕЛЫМИ ФРАЗАМИ — то есть так, как
      // связи не находят. Отсюда: короткое (похоже на имя) — по связям,
      // длинное — вектором. Якорь всегда короткий, и это ему на пользу.
      const words = q.split(/\s+/).filter(Boolean).length
      const mode = words <= 3 ? "local" : "naive"
      // 🔒 БЕРЁМ КОНТЕКСТ, А НЕ СОЧИНЁННЫЙ ДВИЖКОМ ОТВЕТ: 551 мс против 7533 мс
      // и вшестеро больше данных. Сочиняет ответ человеку наш агент.
      const answer = await ask(q, mode, { context: true })
      const text = String(answer.answer ?? "").trim()
      if (!answer.available || !text) continue
      items.push({
        // 🔒 ЗНАНИЕ ОБ ОКРУЖЕНИИ — НЕ ФАКТ О ЧЕЛОВЕКЕ: оно собрано по всем
        // историям, и субъекта у него нет (162-2).
        about: "all-records",
        at: null,
        // 🔒 ПОМЕТКА ЧЕСТНАЯ ПО УСТРОЙСТВУ, А НЕ ПО ДОБРОЙ ВОЛЕ ЗОВУЩЕГО: это
        // собрано из связей, а не сказано человеком (§8.3 стандарта).
        basis: `найдено в связях по имени «${q}», а не записано человеком`,
        claim: "guess",
        from: "связи знания об окружении",
        key: "surroundings",
        scope: null,
        title: `Знание об окружении: ${q}`,
        value: text,
        // 🔒 СПРОШЕНО ФРАЗОЙ ЧЕЛОВЕКА, А НЕ ИМЕНЕМ С УРОВНЯ 1 — ЗНАЧИТ СЛАБОЕ (165-3).
        // Это не «плохая находка»: вектор по фразе находит то, чего связи по
        // именам не находят (измерено 161-3). Но такой кусок пришёл ПО ПОХОЖЕСТИ,
        // и выдавать его за ответ на заданный вопрос нельзя — на нём и держится
        // разница между `answered` и `partial`.
        weak: known.includes(q) ? undefined : true,
      })
    }
    levels.push({
      added: items.length - before,
      anchors: asking,
      level: 2,
      ms: Date.now() - started,
      name: LEVELS[1].name,
      // 🔒 ОТСЕЯННОЕ НАЗЫВАЕТСЯ ПОИМЁННО. «Про Дениса связи ничего не знают» —
      // это ответ, с которым можно работать; молча пропущенное имя неотличимо от
      // имени, которое мы не рассматривали.
      note:
        anchors.length === 0
          ? "имён на уровне 1 не нашлось — спрошено словами человека"
          : known.length === 0
            ? `связи не знают ни одного имени с уровня 1 (${unknown.join(", ")}) — спрошено только словами человека`
            : unknown.length > 0
              ? `спрошено именами, которые связи знают, и словами человека; отсеяны как незнакомые: ${unknown.join(", ")}`
              : "спрошено именами, найденными на уровне 1, и словами человека",
    })
  }

  // ── УРОВЕНЬ 3: ПОХОЖЕЕ ПО СМЫСЛУ, СПРОШЕННОЕ ОБЛАКОМ МЕТОК (162-8) ────────
  //
  // 🎯 ВТОРОЙ СТЫК ЦЕПОЧКИ, СЛОВАМИ ВЛАДЕЛЬЦА: «собирает облако тегов из всех
  // найденных упоминаний и кидает его в классическую векторную базу».
  //
  // 🔒 ОБЛАКО СОБИРАЕТСЯ ИЗ ИМЁН, А НЕ ИЗ РАЗБОРА ЧУЖОГО ОТВЕТА. Метки, которые
  // граф подтвердил на уровне 2, плюс метки, найденные по значимым словам самого
  // вопроса. Разбирать формат чужого контекста было бы привязкой к чужой
  // формулировке — она изменится молча, и разбор станет врать, не сломавшись.
  // 🛑 ВОПРОС ЧЕЛОВЕКА ОСТАЁТСЯ В ЗАПРОСЕ: облако его дополняет. Замена вопроса
  // найденным уже оплачена один раз в 162-3 — потерянной находкой.
  // 🔒 ДОРОГОЙ УРОВЕНЬ НЕ НАЧИНАЕТСЯ БЕЗ РАЗРЕШЕНИЯ, А НЕ ВЫПОЛНЯЕТСЯ И
  // ОТБРАСЫВАЕТСЯ (162-4). Отказ стоит десятки миллисекунд — человек не ждёт того,
  // на что не соглашался.
  const wantsExpensive = depth >= 3 && Boolean(query)
  const blocked = wantsExpensive && LEVELS[2].needsApproval && !approved
  if (blocked) {
    levels.push({
      added: 0,
      level: 3,
      ms: 0,
      name: LEVELS[2].name,
      // 🔒 ОТКАЗ НАЗЫВАЕТ ЦЕНУ И ЧТО ИМЕННО ДАСТ УГЛУБЛЕНИЕ. «Нельзя» без «а что
      // за это будет» человек прочтёт как поломку, а спросить его будет уже не о чем.
      note:
        `не выполнен: нужно согласие человека. Это ${LEVELS[2].what}, около ` +
        `${Math.round(LEVELS[2].ms / 1000)} с. Спроси его и позови ещё раз с approved: true`,
    })
  }
  if (wantsExpensive && !blocked) {
    const started = Date.now()
    const before = items.length
    const cloud = [...askedLabels]
    for (const w of query.split(/\s+/).filter(w => w.length >= NAME_PREFIX).slice(0, 3)) {
      const found = await labelSearch(w, 2)
      for (const l of found) if (!cloud.includes(l)) cloud.push(l)
    }
    const vectorQuery = cloud.length > 0 ? `${query} ${cloud.join(" ")}` : query
    const answer = await ask(vectorQuery, "naive", { context: true })
    const text = String(answer.answer ?? "").trim()
    if (answer.available && text) {
      items.push({
        about: "all-records",
        at: null,
        basis: "найдено вектором по смыслу вопроса, а не записано человеком",
        claim: "guess",
        from: "вектор по складу историй",
        key: "similar",
        scope: null,
        title: "Похожее по смыслу",
        value: text,
      })
    }
    levels.push({
      added: items.length - before,
      anchors: cloud,
      level: 3,
      ms: Date.now() - started,
      name: LEVELS[2].name,
      note:
        cloud.length > 0
          ? "спрошено словами человека и облаком меток, подтверждённых графом"
          : "облако меток пустое: граф не знает ни одного имени из вопроса — спрошено словами человека",
    })
  }

  // ── ПРЕДЛОЖИТЬ ЗАФИКСИРОВАТЬ НАЙДЕННОЕ НА ГЛУБИНЕ (162-9) ────────────────
  //
  // 🎯 СЛОВО ВЛАДЕЛЬЦА: «после реализации ответа должен прямо спросить у
  // пользователя: хотел бы ты зафиксировать результаты этого исследования в
  // памяти верхнего уровня для быстрого доступа в следующий раз?»
  //
  // 🔒 ПРЕДЛОЖЕНИЕ ПОЯВЛЯЕТСЯ ТОЛЬКО ТАМ, ГДЕ БЫЛО ИССЛЕДОВАНИЕ. Ответ, целиком
  // взятый из записанного, фиксировать не в чем: он уже наверху и уже мгновенный.
  // Спрашивать про него значило бы приучить человека отвечать «нет» не глядя.
  // 🛑 ЗАПИСЬ НЕ ДЕЛАЕТСЯ ЗДЕСЬ. Здесь только вопрос; пишет `write` с родом
  // `research` — и только после «да». Молчание согласием не является.
  // ── ЗНАКОМСТВО: ПАМЯТЬ САМА ГОВОРИТ, ЧЕГО О ЧЕЛОВЕКЕ НЕ ЗНАЕТ (163-2) ────
  //
  // 🎯 ВОПРОС ВЛАДЕЛЬЦА: «моё первое общение запускает инструкцию первого
  // знакомства — или такого нет?» Такого не было: навык открывался, только если
  // модель о нём вспомнит. Теперь предложение приходит В ОТВЕТЕ памяти.
  //
  // 🔒 СЧИТАЕТСЯ ТОЛЬКО ТАМ, ГДЕ О ЧЕЛОВЕКЕ НИЧЕГО НЕ НАШЛОСЬ, И СТОИТ ОДНОГО
  // ЧТЕНИЯ. Спрашивать «что известно» на каждом ответе значило бы платить за
  // знакомство в разговоре, где оно давно состоялось.
  // 🛑 И ОНО ИСЧЕЗАЕТ САМО: как только человек назвал признак, следующий вопрос
  // становится другим, а когда названы все — предложения нет вовсе.
  // ✗ ПЕРВАЯ РЕДАКЦИЯ СЧИТАЛА ЭТО ТОЛЬКО ПРИ ПОЛНОСТЬЮ ПУСТОМ ОТВЕТЕ — и прибор
  // 163-2 поймал дефект замысла: стоило человеку назвать ОДНО, предложение
  // исчезало целиком. Знакомство — это очередь, а не единственный вопрос при
  // первой встрече; оно кончается, когда названы ВСЕ признаки очереди.
  // 🔒 СПУТНИКИ ОТВЕТА СЧИТАЮТСЯ ОДНОВРЕМЕННО, А НЕ ДРУГ ЗА ДРУГОМ.
  //
  // ✗ ИЗМЕРЕНО 2026-09-08, И ЭТО МОЙ ЖЕ ДЕФЕКТ ИЗ 163-2: каждое чтение делало
  // ТРИ последовательных похода в слой данных — само значение, список признаков
  // для очереди знакомства и язык человека. Обычный ответ стоил 140–300 мс, но
  // всплески доходили до **1551 мс** — то есть «мгновенный первый уровень»
  // временами переставал быть мгновенным. Причина не в базе, а в сложении задержек.
  // 🔒 ЗАПРОС ЯЗЫКА ОДИН НА ОТВЕТ, А НЕ ДВА: он нужен и знакомству, и предложению
  // запомнить находку, и раньше спрашивался обоими по отдельности.
  let acquaint: Acquaint | undefined
  const needLearn = Boolean(query) && items.some(i => i.about === "all-records" && i.claim === "guess")
  const [known, language] = await Promise.all([
    subject === "self" && !selfKeys
      ? recallSubject(subject, { limit: 50 }).then(m =>
          new Set(m.found === true ? m.items.map(v => v.key) : []))
      : Promise.resolve(selfKeys),
    subject === "self" || needLearn ? personLanguage(subject) : Promise.resolve(null),
  ])
  if (subject === "self" && known) {
    acquaint = nextQuestion(known, language) ?? undefined
  }

  let learnOffer: LearnOffer | undefined
  if (needLearn) {
    learnOffer = {
      anchors: askedLabels.length > 0 ? askedLabels : [],
      ask: offerToLearn(language),
      question: query,
      what: "зафиксировать находку глубокого поиска в памяти верхнего уровня",
    }
  }

  // ── БЛОКИРУЮЩАЯ НЕХВАТКА: ЧЕГО НЕ ХВАТАЕТ ДЛЯ САМОЙ РАБОТЫ (165-5) ────────
  //
  // 🔒 ВЫВОДИТСЯ ИЗ ОБЪЯВЛЕННОЙ ЗАВИСИМОСТИ, А НЕ ИЗ СЛОВ ВОПРОСА. ✗ измерено
  // 2026-09-09: «поставь срок на завтра» находило недостающий часовой пояс, а
  // «напомни мне завтра в девять» — нет; задача одна, разница в формулировке.
  // Теперь `intent.schedule` объявляет `requires: ["person.timezone"]`, и вопрос
  // человеку возникает от требования, а не от совпадения слов.
  // 🛑 ЧИТАЕМ ТОЛЬКО ТОГДА, КОГДА ТРЕБОВАНИЕ ЕСТЬ: у вопроса без зависимостей
  // лишнего похода в слой данных не возникает вовсе.
  let needs: Needs | undefined
  const required = [...new Set(hits.flatMap(h => h.requires))].filter(Boolean)
  if (required.length > 0) {
    const have = new Set(items.filter(i => i.about === "self").map(i => i.key))
    for (const need of required) {
      if (have.has(need)) continue
      const got = await recall(need, { limit: 1, subject })
      if (got.found === true && got.items.length > 0) continue
      // 🛑 НЕТ ГОТОВОЙ ФРАЗЫ — НЕТ ВОПРОСА, И ЭТО НАШ ДОЛГ, А НЕ ПОВОД ВЫДУМАТЬ.
      // Тот же закон, что у знакомства: сочинённый на ходу вопрос звучит анкетой.
      const words = askFor(need, language)
      if (!words) continue
      needs = {
        ask: words.ask,
        for: hits.find(h => h.requires.includes(need))?.key ?? "",
        key: need,
        why: words.why,
      }
      break
    }
  }

  // ── ИСХОД: ОДНО СЛОВО ПРО ОТВЕТ ЦЕЛИКОМ (165-4) ──────────────────────────
  //
  // 🔒 ПОРЯДОК ПРОВЕРОК — ЭТО И ЕСТЬ СМЫСЛ ПОЛЯ. Блокирующая нехватка важнее
  // любой находки: ответить наполовину на работу, которую нельзя сделать, хуже,
  // чем сразу назвать недостающее. Дальше — отвечали ли мы на ЗАДАННЫЙ вопрос
  // (сильное совпадение на уровне 1) или принесли похожее.
  // 🛑 «НЕ ПРО ПАМЯТЬ» И «ИСКАЛИ И НЕ НАШЛИ» РАЗВЕДЕНЫ НАМЕРЕННО: первое значит,
  // что ни один признак реестра не признал вопрос своим (спрашивают у мира),
  // второе — что предмет наш, а значений нет. Слитые в одно «не найдено», они
  // одинаково останавливают следующий шаг, хотя шаги эти разные.
  const direct = items.filter(i => i.weak !== true && i.key !== "surroundings")
  const outcome: Outcome = needs
    ? "needs-human"
    : direct.length > 0
      ? "answered"
      : items.length > 0
        ? "partial"
        : !key && hits.length === 0
          ? "not-mine"
          : "nothing-known"

  if (items.length > 0) {
    return {
      deeper: depth >= MAX_DEPTH ? noDeeper : offer,
      found: true,
      acquaint,
      items,
      learn: learnOffer,
      levels,
      looked,
      missing,
      needs,
      outcome,
      subject,
      total: items.length,
    }
  }

  // 🔒 «НИЧЕГО НЕ ЗНАЮ» — ЗАКОННЫЙ ОТВЕТ, И ОН НАЗЫВАЕТ, ПО ЧЕМУ ИСКАЛИ.
  // Пустота без этого читается как поломка, и следующий шаг делать не из чего.
  //
  // 🔒 «ПРИЗНАКА НЕТ» И «ЗНАЧЕНИЙ НЕТ» — РАЗНЫЕ ОТВЕТЫ, И РАЗНИЦА НАЙДЕНА
  // ИЗМЕРЕНИЕМ 162-1: выдуманный ключ `person.nosuchkey_zzz` получал в ответ
  // «признак есть, значений у него пока нет» — уверенное умолчание вместо
  // честного «такого признака в реестре нет». Читающий останавливал поиск,
  // решив, что спросил правильно и просто рано. Закон 144: уверенное умолчание
  // дороже отсутствующего значения.
  const keyExists = key ? allFacts().some(f => f.key === key) : false
  return {
    acquaint,
    deeper: depth >= MAX_DEPTH ? noDeeper : offer,
    found: false,
    levels,
    looked,
    hint: key
      ? keyExists
        ? "признак есть, значений у него пока нет"
        : "такого признака в реестре нет — проверьте ключ или спросите словами"
      : query
        ? missing.length > 0
          ? "по этим словам смотрели в названные таблицы — значений там нет; причина у каждой в `missing`"
          : "по этим словам в записанном ничего не нашлось"
        : "о человеке пока ничего не записано",
    missing,
    needs,
    outcome,
    searched,
    subject,
  }
}

/**
 * Изменяющий запрос к хранилищу.
 *
 * 🔒 ОТВЕТ ПРОВЕРЯЕТСЯ ДВАЖДЫ: код HTTP и поле `ok` в теле. Слой данных отвечает
 * `200` и `{ok:false}` на отвергнутый SQL — проверка одного лишь кода объявила бы
 * отказ успехом, и правка «прошла бы» молча.
 * ✗ этот же класс оплачен в 143: проглоченный по закону отказ выглядел зелёным.
 */
async function change(sql: string, params: unknown[]): Promise<boolean> {
  try {
    const r = await dataFetch("/db/migrate", { method: "POST", body: JSON.stringify({ params, sql }) })
    if (!r.ok) return false
    const body = (await r.json()) as { ok?: boolean }
    return body.ok !== false
  } catch {
    return false
  }
}

// ── ПРАВКА: ИСТОРИЯ ВМЕСТО ПЕРЕЗАПИСИ (161-4) ──────────────────────────────
//
// 🔒 ЗАКОН 83 ДЕЙСТВУЕТ ЗДЕСЬ БЕЗ ИЗМЕНЕНИЙ: переход пишется НОВОЙ строкой, а
// прежняя помечается прошедшей. Вопрос «когда человек переехал» без истории
// ответа не имеет, а перезапись стирает его молча и навсегда.

export type MemoryMutateResult =
  | { ok: true; key: string; was: unknown; now: unknown; table: string }
  | { ok: false; error: string; hint: string }

export async function mutate(input: {
  key: string
  value: string | Record<string, unknown>
  subject?: string
  why?: string
}): Promise<MemoryMutateResult> {
  const key = String(input.key ?? "").trim().toLowerCase()
  const subject = String(input.subject ?? "").trim() || "self"
  const fact = allFacts().find(f => f.key === key)
  if (!fact || fact.subject !== "self") {
    return {
      ok: false,
      error: "not-a-person-fact",
      hint: "по этому ключу память о человеке не ведётся",
    }
  }
  const table = factTableName(key)
  if (!table) {
    return { ok: false, error: "bad-key", hint: "из ключа не собирается имя хранилища" }
  }

  // 🔒 ПРЕЖНЕЕ ЧИТАЕТСЯ ДО ПРАВКИ, И ЭТО НЕ ФОРМАЛЬНОСТЬ: ответ обязан показать,
  // ЧТО именно заменено. Правка, не назвавшая прежнего, неотличима от новой
  // записи — и человек не сможет сказать «нет, верни как было».
  const current = await recall(key, { limit: 1, subject })
  if (current.found !== true || current.items.length === 0) {
    return {
      ok: false,
      error: "nothing-to-change",
      // 🔒 ЭТО НЕ ОШИБКА ЧЕЛОВЕКА, А ДРУГАЯ ОПЕРАЦИЯ, И ОТКАЗ НАЗЫВАЕТ ЕЁ.
      hint: "правого значения ещё нет — это запись, а не правка: запиши обычным способом",
    }
  }
  const was = current.items[0].value
  const wasId = current.items[0].id

  // 🛑 КОЛОНКИ ПОИМЁННО, БЕЗ `SELECT *` И БЕЗ ПОЗИЦИЙ (закон 83).
  const closed = await change(`UPDATE ${table} SET status = ? WHERE id = ?`, ["past", wasId])
  if (!closed) {
    return { ok: false, error: "close-failed", hint: "прежнее значение не удалось пометить прошедшим" }
  }

  // 🔒 ПРИЧИНА ПРАВКИ ЕДЕТ В `source`, А НЕ В `basis`. `basis` уже означает
  // «на чём стоит ПРЕДПОЛОЖЕНИЕ» (161-2); дать ему второе значение — тот самый
  // класс ошибки, от которого проект избавлялся трижды за три дня: одно слово,
  // два смысла, и через месяц никто не помнит, какой из них здесь.
  const why = String(input.why ?? "").trim()
  const written = await writeFact({
    key,
    source: why ? `человек поправил: ${why}` : "человек поправил",
    subject,
    value: input.value,
  })
  if (!written.ok) {
    // 🛑 ПРЕЖНЕЕ УЖЕ ПОМЕЧЕНО ПРОШЕДШИМ, А НОВОЕ НЕ ЛЕГЛО — ЭТО НАЗЫВАЕТСЯ ВСЛУХ.
    // Молчаливый отказ здесь оставил бы человека вообще без значения, и он узнал
    // бы об этом, спросив систему через неделю.
    return {
      ok: false,
      error: written.error,
      hint: `${written.hint}. Прежнее значение уже помечено прошедшим — запиши новое отдельно`,
    }
  }
  return { ok: true, key, now: input.value, table, was }
}

// ── ЗАБЫТЬ: ПРАВО ЧЕЛОВЕКА, А НЕ ФУНКЦИЯ СИСТЕМЫ (161-5) ───────────────────
//
// 🔒 СИСТЕМА, У КОТОРОЙ ЕСТЬ ТОЛЬКО ЗАПИСЬ, ОДНАЖДЫ СТАНОВИТСЯ ТЕМ, ИЗ ЧЕГО
// НЕЛЬЗЯ УЙТИ (§10.2). Поэтому удаление настоящее, а не пометка: «удалено, но
// лежит» есть ложь о выполненном требовании человека.
//
// 🛑 УДАЛЯЕТСЯ ЗНАЧЕНИЕ, НО НИКОГДА ОПРЕДЕЛЕНИЕ. Определение принадлежит системе
// и описывает, что она УМЕЕТ запоминать; удалив его, мы стёрли бы заодно чужие
// данные того же рода (§3ж).

export type MemoryForgetResult =
  | {
      ok: true
      key: string
      removed: number
      table: string
      definitionKept: true
      /** Что забыто в связях: по каким именам искали и сколько документов убрано (162-5). */
      links?: { anchors: string[]; deleted: number; looked: number; refused?: string }
    }
  | { ok: false; error: string; hint: string }

/**
 * Забыть — в личной памяти, в связях или в обоих (162-5).
 *
 * 🔒 ГЛУБИНА У ЗАБЫВАНИЯ ЗНАЧИТ «И В СВЯЗЯХ ТОЖЕ», И ЭТО ПРЯМОЙ ОТВЕТ ВЛАДЕЛЬЦА
 * НА ВОПРОС ОБ ИЗВЛЕЧЕНИИ: глубина у всех четырёх глаголов, а не только у чтения.
 * Без этого просьба «забудь про Дениса» стирала бы строку в таблице и оставляла
 * историю о нём в связях — то есть система отвечала бы «забыл» и продолжала знать.
 *
 * 🛑 УДАЛЯЕТСЯ ТОЛЬКО СВОЁ, ПО СВОЕЙ МЕТКЕ. Документы связей ищутся по имени
 * источника `memory/<якорь>-`, которое печатаем мы сами при записи. Чужое —
 * сообщения, файлы, чьи-то другие документы — не трогается никогда.
 * 🔒 УДАЛЁННОЕ НАЗЫВАЕТСЯ ЧИСЛОМ: «забыл» без числа неотличимо от «не нашёл, что
 * забывать», а разница здесь и есть ответ человеку.
 */
export async function forget(input: {
  key?: string
  anchors?: string[]
  subject?: string
  id?: number
  depth?: number
}): Promise<MemoryForgetResult> {
  const key = String(input.key ?? "").trim().toLowerCase()
  const subject = String(input.subject ?? "").trim() || "self"
  const asked = (Array.isArray(input.anchors) ? input.anchors : [])
    .filter(a => typeof a === "string" && a.trim())
    .map(a => a.trim())
  const deepForget = Number(input.depth) >= 2 || asked.length > 0

  // ── ТОЛЬКО СВЯЗИ: КЛЮЧА НЕТ, ЕСТЬ ИМЕНА ────────────────────────────────
  //
  // 🔒 ИСТОРИЯ ОБ ОКРУЖЕНИИ ЖИВЁТ БЕЗ КЛЮЧА ПРИЗНАКА, И ЗАБЫВАТЬ ЕЁ НАДО ПО
  // ИМЕНИ. Требовать ключ здесь значило бы отказать в законной просьбе «забудь
  // про Дениса»: такого признака в реестре нет и быть не должно.
  if (!key && asked.length > 0) {
    const gone = await forgetLinks(asked)
    // 🛑 ОТКАЗ ХРАНИЛИЩА — ЭТО НЕ УСПЕХ С НУЛЁМ. Человек попросил забыть; если не
    // забыто, он обязан узнать это словами и с дорогой, а не получить «готово».
    if (gone.deleted === 0 && gone.refused) {
      return {
        ok: false,
        error: gone.refused,
        hint:
          gone.refused === "busy"
            ? "хранилище связей занято обработкой — история НЕ забыта, повтори через несколько секунд"
            : "хранилище связей не выполнило удаление — история не забыта",
      }
    }
    return {
      definitionKept: true,
      key: "",
      links: gone,
      ok: true,
      removed: 0,
      table: "",
    }
  }

  const fact = allFacts().find(f => f.key === key)
  if (!fact) {
    return {
      ok: false,
      error: "unknown-fact",
      hint: key
        ? "такого признака в реестре нет — забывать нечего"
        : "не назван ни ключ признака, ни имена, о ком забыть",
    }
  }
  if (fact.subject !== "self") {
    return {
      ok: false,
      error: "not-a-person-fact",
      hint: "по этому ключу память о человеке не ведётся",
    }
  }
  const table = factTableName(key)
  if (!table) {
    return { ok: false, error: "bad-key", hint: "из ключа не собирается имя хранилища" }
  }

  const before = await recall(key, { limit: 50, subject })
  const had = before.found === true ? before.items.length : 0
  if (had === 0) {
    return { ok: false, error: "nothing-to-forget", hint: "значений по этому ключу нет" }
  }

  const one = typeof input.id === "number" && Number.isInteger(input.id) ? input.id : null
  const sql = one
    ? `DELETE FROM ${table} WHERE id = ? AND subject_key = ?`
    : `DELETE FROM ${table} WHERE subject_key = ?`
  const params = one ? [one, subject] : [subject]
  const done = await change(sql, params)
  if (!done) {
    return { ok: false, error: "delete-failed", hint: "хранилище не выполнило удаление" }
  }

  // 🔒 СЧИТАЕМ ПО ФАКТУ, А НЕ ПО ОБЕЩАНИЮ ХРАНИЛИЩА. «Удалено N» из ответа чужой
  // службы — её слово о себе; разница «было минус осталось» — наше измерение.
  const after = await recall(key, { limit: 50, subject })
  const left = after.found === true ? after.items.length : 0

  // 🔒 ГЛУБИНА 2: ЗАБЫВАЕМ И ИСТОРИИ, ПРИВЯЗАННЫЕ К ЭТИМ ЗНАЧЕНИЯМ. Имена берутся
  // из того, что БЫЛО записано, — «забудь про важных людей» обязано убрать и
  // рассказы о них. 🛑 Имена названы в ответе поимённо: молчаливое удаление по
  // выведенному списку — худший вид удаления, потому что его нельзя обжаловать.
  let links: { anchors: string[]; deleted: number; looked: number; refused?: string } | undefined
  if (deepForget) {
    const names = before.found === true
      ? before.items
          .map(v => (typeof v.value === "string" ? v.value : String((v.value as { name?: unknown })?.name ?? "")))
          .filter(v => v.trim().length >= 2)
      : []
    const all = [...new Set([...asked, ...names])]
    if (all.length > 0) links = await forgetLinks(all)
  }

  return { definitionKept: true, key, links, ok: true, removed: had - left, table }
}

/**
 * Убрать наши документы связей по именам.
 *
 * 🔒 ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ВЕТКА ВНУТРИ `forget`: её зовут два пути — забывание
 * по имени и забывание по ключу с глубиной. Две копии разошлись бы на первом же
 * ужесточении правила «удаляем только своё».
 */
async function forgetLinks(anchors: string[]): Promise<{
  anchors: string[]
  deleted: number
  looked: number
  refused?: string
}> {
  let deleted = 0
  let looked = 0
  let refused: string | undefined
  for (const name of anchors.slice(0, 5)) {
    // 🔒 ОБА НАШИХ ПРЕФИКСА, А НЕ ОДИН (162-9): `memory/` — истории, сказанные
    // человеком, `research/` — блоки дообучения, выведенные системой о том же
    // имени. 🛑 «Забудь про Дениса», оставившее НАШ вывод о Денисе, — это отказ
    // выполнить просьбу, замаскированный под успех.
    // 🛑 ОТКАЗ ХРАНИЛИЩА НЕ ПРОГЛАТЫВАЕТСЯ СБОРЩИКОМ, И ЭТО ОПЛАЧЕНО ЗДЕСЬ ЖЕ.
    // ✗ ИЗМЕРЕНО 2026-09-08: пока движок обрабатывает свежий документ, он отвечает
    // `{"status":"busy","message":"Cannot delete documents while pipeline is busy"}`.
    // `forgetDocuments` возвращал это причиной, а сборщик считал только удалённые —
    // и наружу уходило `ok: true, deleted: 0`, то есть «забыл» при живой истории.
    // Ровно тот класс, которым проект платил в 143: отказ, проглоченный по дороге.
    for (const prefix of [`memory/${name}-`, `research/${name}-`, `correction/${name}-`]) {
      // 🔒 УДАЛЕНИЯ ИДУТ ОДНО ЗА ДРУГИМ, А ДВИЖОК ПОСЛЕ ПЕРВОГО ЗАНЯТ — ЗНАЧИТ
      // ЖДЁМ И ПОВТОРЯЕМ, А НЕ СЧИТАЕМ УДАЛЁННЫМ.
      // ✗ ОПЛАЧЕНО ПРИБОРОМ 162-10 В ТОТ ЖЕ ЧАС: «забудь про N» убирало вывод и
      // МОЛЧА не убирало опровержение — второй вызов приходил, пока первый ещё
      // обрабатывался, получал `busy`, и наружу уходило «удалено 1» вместо двух.
      // Тот же класс проглоченного отказа, что и в 162-5, только этажом выше:
      // причина возвращалась, но частичный успех её перекрывал.
      let one = await forgetDocuments(prefix)
      for (let attempt = 0; attempt < 8 && one.error === "busy"; attempt += 1) {
        await new Promise(r => setTimeout(r, 1000))
        one = await forgetDocuments(prefix)
      }
      deleted += one.deleted.length
      looked = Math.max(looked, one.looked)
      if (one.error && !refused) refused = one.error
    }
  }
  return { anchors, deleted, looked, refused }
}
