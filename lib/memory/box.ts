// ВНУТРЕННОСТИ ЧЁРНОГО ЯЩИКА ПАМЯТИ (161-1, стандарт памяти §10).
//
// 🔒 ЗДЕСЬ ЖИВЁТ ТО, ЧЕГО АГЕНТ ЗНАТЬ НЕ ДОЛЖЕН: сколько у памяти источников,
// как они называются и во что обходятся. Снаружи — четыре глагола.
//
// 🔒 ПОЧЕМУ ЭТО ВАЖНЕЕ УДОБСТВА: правило, живущее в инструкции агента, исполняется
// РОВНО НАСТОЛЬКО, насколько модель его помнит в этот ход. Правило, живущее в
// коде, исполняется всегда. §10.5 стандарта прямо велит переносить сюда всё, что
// сегодня написано словами для агента, — и называет такие правила временными лесами.

/** Куда легла запись. Наружу уезжает словами человека, а не именем хранилища. */
export type MemoryPlace = "personal" | "surroundings"

export type MemoryWriteInput = {
  what: string | Record<string, unknown>
  key?: string
  anchors?: string[]
  claim?: string
  basis?: string
  source?: string
  automationId?: number | null
  /** Чей это факт: сам человек по умолчанию, либо кто-то из его окружения (165-1). */
  subject?: string
  /** Где факт верен: ключ другого признака. Пусто значит «не знаю где» (165-1, закон 141). */
  scope?: string
  /** Блок дообучения: находка глубины, которую человек согласился зафиксировать (162-9). */
  research?: ResearchInput
  /** Человек сказал «да» на предложение зафиксировать. Без этого род `research` не пишется. */
  confirmed?: boolean
  /**
   * Опровержение человека (162-10): что неверно, как на самом деле, чего не поняли.
   *
   * 🔒 РАЗРЕШЕНИЯ НЕ ТРЕБУЕТ — возражение и есть команда запомнить.
   */
  correction?: CorrectionInput
}

export type MemoryWriteResult =
  | { ok: true; where: MemoryPlace; stored: string; hint?: string; unknownAnchors?: string[] }
  | { ok: false; error: string; hint: string; candidates?: string[] }

/**
 * Записать в память.
 *
 * 🔒 РЕШЕНИЕ «КУДА» ПРИНИМАЕТ ЯЩИК, А НЕ ЗОВУЩИЙ. Это и есть весь смысл: до
 * шага 161 агент обязан был сам выбрать между `registry_remember` и дверью
 * знаний, то есть знать, что хранилищ два, и не ошибиться.
 *
 * 🛑 И ИМЕННО ЗДЕСЬ ЭТО СЛОМАЛОСЬ: инструкция велела звать `mcp__intake__knowledge`,
 * а такого инструмента в `tools/list` не было НИ ОДНОГО ДНЯ (найдено 161-1).
 * Дверь знаний работала, прибор был зелёным — он звал её напрямую. Пятый случай
 * «построено и не подключено» за три дня.
 */
export async function write(input: MemoryWriteInput): Promise<MemoryWriteResult> {
  const key = String(input.key ?? "").trim().toLowerCase()
  const anchors = (Array.isArray(input.anchors) ? input.anchors : [])
    .filter(a => typeof a === "string" && a.trim())
    .map(a => a.trim())
  const cell = valueToCell(input.what)

  // 🔒 У БЛОКА ДООБУЧЕНИЯ СВОЙ ВХОД, И ПРОВЕРКА «ЗНАЧЕНИЕ ПУСТОЕ» К НЕМУ НЕ
  // ОТНОСИТСЯ: его текст СОБИРАЕТСЯ из вопроса, ответа и основания, а не приходит
  // полем `what`. Поставь я эту ветку после проверки — фиксация требовала бы
  // лишнего аргумента, который никто не читает.
  if (input.research) {
    return writeResearch(input)
  }

  // 🔒 ОТРИЦАТЕЛЬНОЕ ДООБУЧЕНИЕ ИДЁТ БЕЗ РАЗРЕШЕНИЯ (162-10) — и это единственное
  // место в ящике, где запись не спрашивает ничего. Причина словами владельца:
  // «сам тот факт, что он ответил в отрицательной форме, уже является командой».
  if (input.correction) {
    return writeCorrection(input)
  }

  if (!cell) {
    return { ok: false, error: "empty", hint: "нечего запоминать: значение пустое" }
  }

  // ── РОД ЗАПИСИ (161-2) ────────────────────────────────────────────────────
  //
  // 🔒 ЯЩИК ПРОПУСКАЕТ РОД К ПИСАТЕЛЮ, А ПРОВЕРЯЕТ ЕГО ПИСАТЕЛЬ. Проверка здесь
  // означала бы вторую границу рядом с первой: обойти писателя нельзя, обойти
  // ящик — можно, и слабейшая проверка стала бы настоящей.
  const claim = String(input.claim ?? "").trim()

  // ── ОДНО ИЗ ДВУХ, А НЕ ОБА ────────────────────────────────────────────────
  //
  // 🔒 ОТКАЗ, А НЕ ВЫБОР ПО СТАРШИНСТВУ. Пришли и ключ, и якоря — вызывающий сам
  // не знает, о ком эта запись. Выбрать за него значит записать не туда молча, а
  // молчаливая ошибка памяти обнаруживается через месяц пустым ответом.
  if (key && anchors.length > 0) {
    return {
      ok: false,
      error: "both-key-and-anchors",
      hint:
        "назови одно: `key` — если это факт о самом человеке, `anchors` — если это история о ком-то из его окружения",
    }
  }

  // ── БЛОК ДООБУЧЕНИЯ: НАХОДКА ГЛУБИНЫ, ПОДТВЕРЖДЁННАЯ ЧЕЛОВЕКОМ (162-9) ────
  //
  // 🎯 СЛОВО ВЛАДЕЛЬЦА: «когда пользователь говорит да, мы формируем ответ,
  // который явно должен указывать, что в автоматизации номер 124 было получено
  // глубинное исследование… Примерно такой блок дообучения ложится в граф и
  // запускается его процесс обработки, одновременно с этим этот объект хранится
  // в векторной базе».
  //
  // 🛑 ПИШЕТСЯ ТОЛЬКО ПОСЛЕ «ДА» ЧЕЛОВЕКА, И ПРОВЕРЯЕТСЯ ЭТО ЗДЕСЬ, А НЕ В
  // ИНСТРУКЦИИ АГЕНТА: правило, живущее в словах, исполняется настолько,
  // насколько модель помнит его в этот ход. Без `confirmed: true` — отказ.
  async function writeResearch(input: MemoryWriteInput): Promise<MemoryWriteResult> {
    const anchors = (Array.isArray(input.anchors) ? input.anchors : [])
      .filter(a => typeof a === "string" && a.trim())
      .map(a => a.trim())
    const r = input.research as ResearchInput
    if (input.confirmed !== true) {
      return {
        ok: false,
        error: "not-confirmed",
        hint:
          "находку глубины фиксируем только после «да» человека: спроси его словами из `learn.ask` " +
          "и позови ещё раз с confirmed: true",
      }
    }
    const anchorsFor = anchors.length > 0 ? anchors : r.anchors
    if (anchorsFor.length === 0) {
      // 🔒 БЕЗ ЯКОРЯ ЗАПИСЬ НЕ НАЙДЁТСЯ НИКОГДА — тот же закон, что у историй.
      return {
        ok: false,
        error: "no-anchors",
        hint: "назови имена, к которым относится находка: без якоря её потом не найти",
      }
    }
    // 🛑 НОМЕР АВТОМАТИЗАЦИИ ЕДЕТ ОТДЕЛЬНЫМ ПОЛЕМ ЗАПРОСА, А НЕ ВНУТРИ БЛОКА, И
    // ЕГО НАДО ПЕРЕДАТЬ ЯВНО. ✗ поймано первым прогоном прибора: блок собирался
    // без номера и писал «в работе вне автоматизации» при переданном 124 —
    // присланное молча ничего не делало (закон 143).
    const text = composeResearch({ ...r, anchors: anchorsFor, automationId: input.automationId ?? null })
    // 🔒 ИСТОЧНИК ОТЛИЧАЕТСЯ ОТ ИСТОРИЙ (`memory/`) НАМЕРЕННО: `research/` — это
    // наш вывод, а не сказанное человеком, и забывать их надо по отдельности.
    const done = await learn({
      anchors: anchorsFor,
      origin: "глубинное исследование памяти",
      source: `research/${anchorsFor[0]}-${Date.now()}`,
      text,
    })
    if (!done.accepted) {
      return { ok: false, error: done.refused ?? "refused", hint: "блок дообучения не принят хранилищем" }
    }
    return {
      ok: true,
      where: "surroundings",
      stored: text,
      hint:
        "блок дообучения записан: он ложится в граф, его обработка идёт в фоне, и тот же объект " +
        "остаётся в векторе. Вывод остался предположением — произноси его теми же словами",
    }
  }

  /**
   * Записать опровержение человека (162-10).
   *
   * 🛑 ЗДЕСЬ НЕТ ПРОВЕРКИ `confirmed`, И ЭТО НЕ ЗАБЫТО, А РЕШЕНО. Возражение
   * человека само есть команда; переспрашивать «записать ли, что я ошибся?» —
   * значит не слышать сказанное. Асимметрия с `research` намеренная и описана
   * в §6.1а стандарта.
   * 🔒 ИСХОДНЫЙ БЛОК НЕ ТРОГАЕТСЯ ВООБЩЕ: ни удаления, ни правки. Опровержение
   * встаёт рядом на ТОМ ЖЕ ЯКОРЕ — значит вопрос по имени приводит к обоим.
   */
  async function writeCorrection(input: MemoryWriteInput): Promise<MemoryWriteResult> {
    const c = input.correction as CorrectionInput
    const anchorsFor = anchors.length > 0 ? anchors : c.anchors
    if (anchorsFor.length === 0) {
      return {
        ok: false,
        error: "no-anchors",
        hint:
          "назови имена, к которым относится опровержение: оно ищется тем же якорем, что и " +
          "опровергнутое, и без якоря они разойдутся",
      }
    }
    const text = composeCorrection({ ...c, anchors: anchorsFor, automationId: input.automationId ?? null })
    const done = await learn({
      anchors: anchorsFor,
      origin: "опровержение, полученное от человека",
      // 🔒 ТРЕТИЙ НАШ ПРЕФИКС, И ОН ОТЛИЧАЕТСЯ ОТ ДВУХ ПРЕЖНИХ НАМЕРЕННО:
      // `memory/` — сказанное человеком, `research/` — наш вывод, `correction/` —
      // опровержение нашего вывода. Разные роды забываются по отдельности.
      source: `correction/${anchorsFor[0]}-${Date.now()}`,
      text,
    })
    if (!done.accepted) {
      return { ok: false, error: done.refused ?? "refused", hint: "опровержение не принято хранилищем" }
    }
    return {
      ok: true,
      where: "surroundings",
      stored: text,
      hint:
        "опровержение записано без спроса — так и задумано. Прежний вывод НЕ удалён: при следующем " +
        "похожем вопросе произноси их вместе, а не вместо",
    }
  }

  // ── ИСТОРИЯ ОБ ОКРУЖЕНИИ: ЯКОРЯ ЕСТЬ ──────────────────────────────────────
  if (anchors.length > 0) {
    // 🔒 ГРАФ ПРИНИМАЕТ ТЕКСТ, А НЕ ОБЪЕКТ. Объект, свёрнутый в JSON, читается
    // моделью графа как строка со скобками: сущности из него не извлекутся, и
    // запись станет невидимой ровно тем способом, от которого защищает якорь.
    if (typeof input.what !== "string") {
      return {
        ok: false,
        error: "not-text",
        hint: "историю об окружении запиши словами человека, а не объектом полей",
      }
    }
    const source = `memory/${anchors[0]}-${Date.now()}`
    const done = await learn({ anchors, source, text: input.what.trim() })
    if (!done.accepted) {
      return {
        ok: false,
        error: done.refused ?? "refused",
        hint: "знание об окружении не принято хранилищем",
      }
    }
    // 🔒 НАЗЫВАЕТСЯ ВСЛУХ: связи строятся в фоне десятки секунд, и вопрос,
    // заданный сразу, этой записи может не увидеть. Молчание об этом
    // вызывающий прочтёт как «уже доступно» и пообещает человеку лишнее.
    return {
      ok: true,
      where: "surroundings",
      stored: input.what.trim(),
      hint: "записано; связи строятся в фоне — вопрос сразу после записи может этого ещё не найти",
    }
  }

  // ── ФАКТ О ЧЕЛОВЕКЕ: НУЖЕН КЛЮЧ ───────────────────────────────────────────
  //
  // 🔒 КЛЮЧ НЕ УГАДЫВАЕТСЯ, НО ПОДСКАЗЫВАЕТСЯ. Записать по угаданному ключу
  // значит положить значение туда, где его никто не найдёт, и узнать об этом
  // через месяц. Поэтому отказ, но отказ С КАНДИДАТАМИ: механический поиск
  // стоит ноль ходов модели, а вызывающему остаётся выбрать, а не гадать.
  if (!key) {
    const guess = find("facts", typeof input.what === "string" ? input.what : cell, { limit: 5 })
    const candidates = guess.found === true ? guess.items.map(i => i.key) : []
    return {
      ok: false,
      error: "no-key",
      hint:
        candidates.length > 0
          ? "не назван ключ признака; по этим словам подходят: " + candidates.join(", ")
          : "не назван ни ключ признака (факт о человеке), ни якоря (история об окружении)",
      candidates,
    }
  }

  // 🛑 ГРАНИЦУ СТЕРЕЖЁТ ЯЩИК, А НЕ ОБЪЯВЛЕНИЕ (закон 158-5а, перенесён из двери
  // реестра). Ключ приходит от модели; без этой проверки метод стал бы способом
  // дописать что угодно в любую таблицу признаков.
  const fact = allFacts().find(f => f.key === key)
  if (!fact || fact.subject !== "self") {
    return {
      ok: false,
      error: "not-a-person-fact",
      hint: "по этому ключу память о человеке не ведётся; ключ берут из поиска по его словам",
    }
  }

  // 🔒 СУБЪЕКТ И ОХВАТ ОТКРЫТЫ СНАРУЖИ (165-1), И ЭТО НЕ НОВАЯ СПОСОБНОСТЬ, А
  // СНЯТАЯ ЗАГЛУШКА: колонки `subject_key` (шаг 83) и `scope_key` (шаг 141) есть
  // у всех признаков, писатель их принимает, а дверь агента писала «self» жёстко
  // и охват не передавала вовсе. Измерено 2026-09-09: записать факт о третьем
  // лице или указать область истинности было НЕЧЕМ.
  // 🛑 УМОЛЧАНИЕ ПРЕЖНЕЕ: не назвали — значит про самого человека. Иначе каждый
  // прежний вызов сменил бы смысл молча.
  const subject = String(input.subject ?? "").trim() || "self"
  const scope = String(input.scope ?? "").trim() || null
  const written = await writeFact({
    automationId: input.automationId ?? null,
    basis: input.basis ?? null,
    claim: (claim || null) as FactClaim | null,
    key,
    scope,
    source: input.source ?? "сказано человеком в переписке",
    subject,
    // 🔒 ЗНАЧЕНИЕ ПЕРЕДАЁТСЯ КАК ЕСТЬ, БЕЗ ПРИВЕДЕНИЯ К СТРОКЕ. Приведение типа
    // ПЕРЕД проверкой обезоруживает проверку — закон, оплаченный в 160 тем, что
    // объект становился строкой до сторожа глубины и проходил его насквозь.
    value: input.what,
  })

  if (!written.ok) {
    // 🔒 ОТКАЗ ГЛУБИНЫ НАЗЫВАЕТ ДОРОГУ, А НЕ ТОЛЬКО ЗАПРЕТ. «Нельзя» без «а как
    // можно» приводит к тому, что вызывающий выбрасывает сказанное человеком.
    const road =
      written.error === "nested-object" || written.error === "second-order-subject"
        ? " Перескажи это словами и назови, о ком речь, — уедет в знание об окружении."
        : ""
    return { ok: false, error: written.error, hint: written.hint + road }
  }

  return { ok: true, stored: cell, where: "personal" }
}

// ── ЧТЕНИЕ: ЛЕСТНИЦА ВНУТРИ ЯЩИКА, БЮДЖЕТ ПАРАМЕТРОМ (161-3) ───────────────
//
// 🔒 ЭТО ВТОРОЙ ДОЛГ §8.2 СТАНДАРТА, И ОН ЗАКРЫВАЕТСЯ ЗДЕСЬ, А НЕ В ИНСТРУКЦИИ.
// Прежде порядок источников и решение «идти ли глубже» жили словами в `CLAUDE.md`
// службы — то есть исполнялись настолько, насколько модель помнила их в этот ход.
// §10.5 называет такие правила временными лесами и велит переносить их внутрь.
//
// 🔒 ЦЕНА УГЛУБЛЕНИЯ ИЗМЕРЕНА, А НЕ ПРИДУМАНА (закон 146): личная таблица — 30 мс,
// вопрос к знанию об окружении режимом `local` — 885 · 4777 · 5016 мс на трёх
// вопросах подряд, замер на сервере 2026-09-08. Отсюда «около пяти секунд»:
// берём худшее измеренное, а не среднее, — обещание должно выполняться в плохом
// случае, иначе оно не обещание.
const DEEP_SECONDS = 5

// ── ЛЕСТНИЦА ГЛУБИНЫ: ЕДИНСТВЕННЫЙ ИСТОЧНИК ПОРЯДКА И ЦЕН (162-3) ──────────
//
// 🎯 ЦЕЛЬ ВЛАДЕЛЬЦА 2026-09-08, ДОСЛОВНО: «мы должны стремиться возвратить
// необходимое количество информации, используя запрос с первого уровня, чтобы
// обеспечить реактивную работу приложения. Только последующие углубления по
// согласованию с пользователем должны намеренно идти в цепочку усложнений».
//
// 🔒 ЛЕСТНИЦА — ЗАПАСНОЙ ПУТЬ, А НЕ ДОСТИЖЕНИЕ. Уровень 1 не зовёт модель вовсе;
// всё дальше платит вектором запроса и временем. Признак того, что цель нарушена,
// проверяемый: доля ответов, отданных уровнем 1. Углубление на каждом втором
// вопросе значит сломанный уровень 1 — мало триггеров, кандидатов или колонок.
//
// 🔒 УРОВНИ КУМУЛЯТИВНЫ: `depth: 3` содержит всё, что дали 1 и 2. «Нашлось» и
// «достаточно» — разные утверждения, и второе решает зовущий, а не ящик.
// ✗ ОПЛАЧЕНО ИЗМЕРЕНИЕМ ДО ПРАВКИ: `if (items.length > 0) return` обрывал
// лестницу на первой находке — кейс «друг Денис → его история в связях» не
// работал НИ ПРИ КАКИХ данных, потому что имя друга находилось уровнем 1.
//
