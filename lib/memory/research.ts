//
// 🎯 СЛОВА ВЛАДЕЛЬЦА 2026-09-08: «по завершению глубинного исследования формируем
// блок дообучающего контекста, и конечно этот дообучающий контекст должен
// вложиться в обучение ПОСЛЕ ПОДТВЕРЖДЕНИЯ ПОЛЬЗОВАТЕЛЯ, ценно ли это… И когда
// пользователь говорит да, мы формируем ответ, который явно должен указывать, что
// в автоматизации номер 124 было получено глубинное исследование…»
//
// 🔒 БЛОК ЛОЖИТСЯ В ГРАФ И В ВЕКТОР, И НИ В КАКУЮ ТАБЛИЦУ. Довод владельца:
// связывать такую запись реляционно не нужно. Таблица под неё заводится ТОЛЬКО
// по прямой просьбе архитектора — и это отдельная работа.
// 🪦 Этим отменена прежняя редакция §6.2 стандарта («в вектор сразу, в граф после
// подтверждения»): она принималась в предположении, что это разные хранилища.
// Измерено 2026-09-08 — движок один, и запись документа строит граф.

export type ResearchInput = {
  /** Вопрос человека ДОСЛОВНО: он же поисковый ключ следующего раза. */
  question: string
  /** Что было получено — вывод, как его произнесли человеку. */
  answer: string
  /** На чём вывод стоит: какие утверждения сложились в цепочку. */
  basis?: string
  /** Номер автоматизации, в ходе которой шло исследование. */
  automationId?: number | null
  /** Имена сущностей первого порядка, через которые запись связана с человеком. */
  anchors: string[]
}

/**
 * Собрать блок дообучения по образцу владельца.
 *
 * 🔒 БЛОК НАЗЫВАЕТ СВОЁ ПРОИСХОЖДЕНИЕ ПЕРВОЙ ЖЕ СТРОКОЙ — номер автоматизации и
 * то, что это ИССЛЕДОВАНИЕ, а не сказанное человеком. Найденный через месяц, он
 * обязан сам объяснить, откуда взялся: запись без происхождения через месяц
 * неотличима от свидетельства человека.
 *
 * 🛑 ВЫВОД ОСТАЁТСЯ ПРЕДПОЛОЖЕНИЕМ, И ЭТО НЕ ОСТОРОЖНОСТЬ, А ЗАКОН §6.3.
 * Подтверждение человека означает «это ценно, зафиксируй», а НЕ «это правда».
 * Слова «следует предположить» и основание остаются в тексте навсегда — иначе
 * фиксация превращается в способ поверить самому себе.
 */
export function composeResearch(input: ResearchInput): string {
  const number = typeof input.automationId === "number" && input.automationId > 0
    ? `автоматизации № ${input.automationId}`
    : "работе вне автоматизации"
  const lines = [
    `В ${number} было получено глубинное исследование памяти.`,
    `Вопрос человека дословно: «${input.question.trim()}».`,
    `Полученный ответ: ${input.answer.trim()}`,
  ]
  if (input.basis && input.basis.trim()) {
    lines.push(`Основание вывода: ${input.basis.trim()}`)
  }
  lines.push(
    "Род записи: предположение, подтверждённое человеком как ценное. Это не свидетельство человека" +
      " и не проверенный факт — при следующем ответе произносить теми же словами, с основанием.",
  )
  if (input.anchors.length > 0) {
    lines.push(`Связано с: ${input.anchors.join(", ")}.`)
  }
  return lines.join("\n")
}

export type CorrectionInput = {
  /** Что именно человек назвал неверным — своими словами или адресом блока. */
  wrong: string
  /** Как на самом деле — со слов человека. */
  right: string
  /** Чего система не поняла: например, спрашивали про другого президента. */
  misunderstood?: string
  /** Вопрос, на который был дан опровергнутый ответ, — если известен. */
  question?: string
  /** Номер автоматизации, в которой прозвучало возражение. */
  automationId?: number | null
  /** Имена, к которым это относится: тот же якорь, что у опровергнутого блока. */
  anchors: string[]
}

/**
 * Собрать блок ОТРИЦАТЕЛЬНОГО дообучения (162-10).
 *
 * 🎯 СЛОВА ВЛАДЕЛЬЦА 2026-09-08: «когда пользователь опровергает информацию,
 * прямо говорит, что это недостоверно, или это не надо использовать, или вообще
 * забудь об этом, — имеет смысл создать обучающий блок, который мы точно так же
 * свяжем с текущим блоком. То есть мы НЕ БУДЕМ УДАЛЯТЬ тот блок, который был
 * исходный, потому что он может нести в себе косвенно другой смысл и в будущем
 * может быть полезен».
 *
 * 🔒 РАЗРЕШЕНИЯ НЕ СПРАШИВАЕТ, И ЭТО ЕГО ГЛАВНОЕ ОТЛИЧИЕ ОТ ПОЛОЖИТЕЛЬНОГО.
 * Слово владельца: «сам тот факт, что он ответил в отрицательной форме, уже
 * является командой о том, что надо запомнить». Спросить «записать ли, что я
 * ошибся?» значит переспросить человека о том, что он только что сказал прямо.
 *
 * 🔒 БЛОК СВЯЗЫВАЕТСЯ С ОПРОВЕРГНУТЫМ ЯКОРЕМ И СЛОВАМИ, А НЕ ЗАМЕНЯЕТ ЕГО.
 * Один и тот же якорь приводит к обоим: вопрос по имени вернёт и предположение,
 * и опровержение. 🛑 Опровержение, не нашедшееся вместе с исходным, ХУЖЕ его
 * отсутствия — система уверенно повторит опровергнутое, имея опровержение на руках.
 */
export function composeCorrection(input: CorrectionInput): string {
  const number = typeof input.automationId === "number" && input.automationId > 0
    ? `автоматизации № ${input.automationId}`
    : "работе вне автоматизации"
  const lines = [
    `ОПРОВЕРЖЕНИЕ, полученное от человека в ${number}.`,
    `Что признано неверным: ${input.wrong.trim()}`,
    `Как на самом деле (со слов человека): ${input.right.trim()}`,
  ]
  if (input.question && input.question.trim()) {
    lines.push(`Опровергнутый ответ был дан на вопрос: «${input.question.trim()}».`)
  }
  if (input.misunderstood && input.misunderstood.trim()) {
    lines.push(`Что было понято неверно: ${input.misunderstood.trim()}`)
  }
  lines.push(
    "Род записи: сказано человеком прямо, разрешения не требовалось. Прежний вывод НЕ УДАЛЁН: он" +
      " может нести другой смысл. При ответе на похожий вопрос это опровержение обязано звучать" +
      " вместе с ним, а не вместо него.",
  )
  if (input.anchors.length > 0) {
    lines.push(`Связано с: ${input.anchors.join(", ")}.`)
  }
  return lines.join("\n")
}

/**
 * Компактный вопрос человеку — предложить зафиксировать находку.
 *
 * 🔒 ДВА ЯЗЫКА, А НЕ 82, И ЭТО ТОТ ЖЕ ЗАКОН, ЧТО У СЛОЯ АРХИТЕКТОРА: сюда приходит
 * хозяин проекта, и он уже пришёл. Язык берётся из `person.language`, а не
 * угадывается по буквам вопроса: человек может спросить по-английски, оставаясь
 * русскоязычным.
 * 🛑 ВОПРОС КОРОТКИЙ НАМЕРЕННО. Владелец просил «компактнее и улучшено»: длинное
 * предложение в конце ответа человек не дочитывает, и предложение перестаёт быть
 * вопросом — становится шумом, на который отвечают молчанием.
 */
export function offerToLearn(lang: string | null | undefined): string {
  const code = String(lang ?? "").trim().slice(0, 2).toLowerCase()
  if (code === "en") {
    return "Worth remembering? Say yes — and next time I answer this instantly."
  }
  return "Запомнить это? Скажи «да» — и в следующий раз отвечу сразу."
}
