// (`tools-registry.tsx`), а описания — пятью объектами в `lib/task/actors.ts`.
// То есть данные жили в разметке, и добавить инструмент значило править экран.
// Теперь данные в конфиге, экран их рисует и ничего о них не знает.
//
// 🔒 ПРАВИЛО ВЛАДЕЛЬЦА, РАДИ КОТОРОГО РЕЕСТР СУЩЕСТВУЕТ: «для каждого действия мы
// создаём свой инструмент, который владеет навыком и умеет делать только одно
// действие». Реестр признаков отвечает, ЧТО извлекать; этот — КТО это делает.
//
// 🛑 СОСТОЯНИЕ «ЗАГЛУШКА» — ПОЛЕ ЗАПИСИ, А НЕ КОММЕНТАРИЙ. Инструмент, который
// отвечает 200 и ничего не делает, выглядит работающим ровно до того дня, когда
// на него понадобится опереться. Поэтому `real: false` стоит рядом с именем и
// доезжает до экрана.

export type Tool = {
  /** Вечное машинное имя. На нём висят ссылки; не меняется никогда. */
  id: string;
  /** Имя в колонке «Инструмент». */
  name: string;
  /** Что умеет — всплывает подсказкой при наведении. */
  what: string;
  /** Текст для колонки «Инструкция», когда инструкция у инструмента своя. */
  ownInstruction: string;
  /** Настоящий или заглушка. Заглушка обязана называть себя заглушкой. */
  real: boolean;
  /** Где в разборе он стоит. */
  where: string;
};

type FileTool = Partial<Record<keyof Tool, unknown>>;

const str = (v: unknown): string => (typeof v === "string" ? v : "");

/**
 * Все инструменты в порядке файла.
 *
 * 🔒 ПОРЯДОК ФАЙЛА — ЭТО ПОРЯДОК ИСПОЛНЕНИЯ В РАЗБОРЕ, А НЕ АЛФАВИТ. Он был
 * таким и в коде; пересортировав здесь, мы соврали бы о том, что за чем идёт.
 * 🔒 ЗАПИСЬ БЕЗ `id` ОТБРАСЫВАЕТСЯ: на `id` висят ссылки, и безымянный
 * инструмент не на что сослать.
 * 🔒 `real` ПО УМОЛЧАНИЮ ЛОЖЬ. Забытое поле обязано читаться как «заглушка», а
 * не как «настоящий»: ошибка в эту сторону видна сразу, в обратную — молчит.
 */
export function allTools(): Tool[] {
  const list = Array.isArray(file?.tools) ? (file.tools as FileTool[]) : [];
  const seen = new Set<string>();
  const out: Tool[] = [];
  for (const r of list) {
    const id = str(r.id).trim();
    if (!id || seen.has(id)) {
      continue;
    }
    seen.add(id);
    out.push({
      id,
      name: str(r.name),
      ownInstruction: str(r.ownInstruction),
      real: r.real === true,
      what: str(r.what),
      where: str(r.where),
    });
  }
  return out;
}

/** Один инструмент по вечному имени. Пусто — записи нет. */
export function toolById(id: string): Tool | undefined {
  return allTools().find((t) => t.id === id);
}
